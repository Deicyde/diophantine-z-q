"""qm-pin §6: structure of (O/3O)^x / {±1} for the maximal order O of B = (2,-3)
(basis of ZInQKernel/HDecomp/QM/Structures.lean: ofInt n = (n0 + n2/2) + (n1 + n3/2) i + (n2/2) j + (n3/2) k,
 i^2 = 2, j^2 = -3, ij = k; product = mulCoord). Checks: |(O/3O)^x| = 72, norm-one subgroup of order 36,
 1+i has norm -1, and whether D = (O/3O)^x/{±1} has an abelian subgroup of index <= 2."""
from itertools import product
from fractions import Fraction as Fr

def mulCoord(n, m):
    return (m[0]*n[0] + 2*m[1]*n[1] + 2*m[1]*n[3] - m[2]*n[2] + 2*m[3]*n[3],
            m[0]*n[1] + m[1]*n[0] + m[1]*n[2] - m[2]*n[3] + m[3]*n[2],
            m[0]*n[2] - 2*m[1]*n[3] + m[2]*n[0] + m[2]*n[2] + 2*m[3]*n[1],
            m[0]*n[3] - m[1]*n[2] + m[2]*n[1] + m[2]*n[3] + m[3]*n[0])

def coords(n):  # quaternion coordinates (a, b, c, d) of ofInt n
    return (Fr(n[0]) + Fr(n[2], 2), Fr(n[1]) + Fr(n[3], 2), Fr(n[2], 2), Fr(n[3], 2))

def qmul(x, y):  # (2,0,-3) quaternion product: i^2=2, j^2=-3, k = ij, k^2 = 6
    a1, b1, c1, d1 = x; a2, b2, c2, d2 = y
    return (a1*a2 + 2*b1*b2 - 3*c1*c2 + 6*d1*d2,
            a1*b2 + b1*a2 + 3*(c1*d2 - d1*c2),
            a1*c2 + c1*a2 + 2*(b1*d2 - d1*b2),
            a1*d2 + d1*a2 + b1*c2 - c1*b2)

# sanity: mulCoord matches the quaternion product on a sample (VERIFIED below)
import random
random.seed(1)
for _ in range(30):
    n = tuple(random.randint(-5, 5) for _ in range(4)); m = tuple(random.randint(-5, 5) for _ in range(4))
    assert qmul(coords(n), coords(m)) == coords(mulCoord(n, m)), (n, m)

def nrd(n):
    a, b, c, d = coords(n)
    v = a*a - 2*b*b + 3*c*c - 6*d*d
    assert v.denominator == 1
    return int(v)

R = list(product(range(3), repeat=4))
red = lambda n: tuple(x % 3 for x in n)
mul = lambda n, m: red(mulCoord(n, m))
one = (1, 0, 0, 0)
units = [x for x in R if any(mul(x, y) == one for y in R)]
print('|(O/3O)^x| =', len(units))
norm1 = [x for x in units if nrd(x) % 3 == 1]
print('norm-one subgroup:', len(norm1))
print('nrd(1+i) =', nrd((1, 1, 0, 0)))
neg = (2, 0, 0, 0)
# quotient by ±1
cls = {}
for x in units:
    key = min(x, mul(x, neg)); cls[x] = key
D = sorted(set(cls.values()))
print('|D| =', len(D))
dmul = lambda x, y: cls[mul(x, y)]
def order(x):
    k, y = 1, x
    while y != cls[one]:
        y = dmul(y, x); k += 1
    return k
orders = {}
for x in D: orders.setdefault(order(x), 0); orders[order(x)] += 1
print('element orders in D:', dict(sorted(orders.items())))
syl3 = [x for x in D if order(x) in (1, 3)]
print('|elements of 3-power order| =', len(syl3))
cent = [x for x in D if all(dmul(x, y) == dmul(y, x) for y in syl3)]
print('|centralizer of Syl3 in D| =', len(cent))
center = [x for x in D if all(dmul(x, y) == dmul(y, x) for y in D)]
print('|Z(D)| =', len(center))
# max abelian subgroup order by brute force over subgroups generated by <= 2 elements (abelian ones)
def gen(gs):
    S = {cls[one]}; frontier = [cls[one]]
    while frontier:
        new = []
        for s in frontier:
            for g in gs:
                t = dmul(s, g)
                if t not in S: S.add(t); new.append(t)
        frontier = new
    return S
best = 0
for x in D:
    for y in D:
        if dmul(x, y) == dmul(y, x):
            best = max(best, len(gen([x, y])))
print('largest abelian subgroup generated by two commuting elements:', best)
# an abelian subgroup of index <= 2 has order >= 18 and contains the (normal, unique) Sylow-3 subgroup,
# so it lies in the centralizer of Syl3; report whether such exists
print('abelian subgroup of index <= 2 exists:', len(cent) >= 18 and all(dmul(a, b) == dmul(b, a) for a in cent for b in cent))
