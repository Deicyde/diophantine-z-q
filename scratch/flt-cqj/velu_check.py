"""Differential check of Anthropic FLT's `WeierstrassCurve.cyclicQuotientJ` (iterated Vélu, as defined in
ZInQKernel/Contrib/CloudB2X0Transitive/Vendor/AnthropicFLT/Definitions/Def_WeierstrassCurve_CyclicQuotientJ.lean,
re-implemented here by reading that file) against PARI's `ellisogeny`, and, for prime N, against the classical
modular polynomial `polmodular(N)`.  Curves over F_p with a rational point P of exact order N; H = <P>.
Run: uv run --offline --with cypari2 python -I scratch/flt-cqj/velu_check.py
"""
import random
import cypari2

pari = cypari2.Pari()
pari.allocatemem(2 * 10**8, silent=True)


def b_invariants(a, p):
    a1, a2, a3, a4, a6 = a
    b2 = (a1 * a1 + 4 * a2) % p
    b4 = (2 * a4 + a1 * a3) % p
    b6 = (a3 * a3 + 4 * a6) % p
    return b2, b4, b6


def curve(a, p):
    return pari.ellinit([pari.Mod(x, p) for x in a])


def points_of_subgroup(E, gens):
    """All points of the subgroup generated by `gens` (closure), as PARI points ([0] = origin)."""
    seen = {str(pari('[0]')): pari('[0]')}
    frontier = [pari('[0]')]
    while frontier:
        new = []
        for Q in frontier:
            for g in gens:
                R = pari.elladd(E, Q, g)
                k = str(R)
                if k not in seen:
                    seen[k] = R
                    new.append(R)
        frontier = new
    return list(seen.values())


def is_zero(Q):
    return len(Q) == 1


def x_of(Q):
    return int(pari.lift(Q[0]))


def step(a, E, H, l, p):
    """One step of `cqjStep`: (stepCurve, stepSubgroup points) for ℓ = l."""
    a1, a2, a3, a4, a6 = a
    b2, b4, b6 = b_invariants(a, p)
    inv = lambda z: pow(z % p, p - 2, p)
    ker = {x_of(Q) for Q in H if not is_zero(Q) and is_zero(pari.ellmul(E, Q, l))}   # kernelXSet
    coker = {x_of(Q) for Q in H if not is_zero(pari.ellmul(E, Q, l))}                 # coKernelXSet
    if l == 2:
        def G(x0):  # xVeluG x0 = veluGx x0 (twoTorsionY x0)
            y0 = (-(a1 * x0 + a3) * inv(2)) % p
            return (3 * x0 * x0 + 2 * a2 * x0 + a4 - a1 * y0) % p
        sT = sum(G(x0) for x0 in ker) % p
        sW = sum(x0 * G(x0) for x0 in ker) % p
        newa = [a1, a2, a3, (a4 - 5 * sT) % p, (a6 - b2 * sT - 7 * sW) % p]
        X = lambda x: (x + sum(G(x0) * inv(x - x0) for x0 in ker)) % p
    else:
        T = lambda x: (6 * x * x + b2 * x + b4) % p
        U = lambda x: (4 * x ** 3 + b2 * x * x + 2 * b4 * x + b6) % p
        W = lambda x: (U(x) + x * T(x)) % p
        sT = sum(T(x0) for x0 in ker) % p
        sW = sum(W(x0) for x0 in ker) % p
        newa = [a1, a2, a3, (a4 - 5 * sT) % p, (a6 - b2 * sT - 7 * sW) % p]
        X = lambda x: (x + sum(T(x0) * inv(x - x0) + U(x0) * inv((x - x0) ** 2) for x0 in ker)) % p
    E2 = curve(newa, p)
    Y = {X(x) for x in coker}
    gens = []
    for x in Y:  # subgroupOfX: closure of the nonzero points with x-coordinate in Y
        ys = pari.ellordinate(E2, pari.Mod(x, p))
        for y in ys:
            gens.append(pari([pari.Mod(x, p), y]))
    H2 = points_of_subgroup(E2, gens) if gens else [pari('[0]')]
    return newa, E2, H2


def cyclic_quotient_j(a, P, N, p):
    """`cyclicQuotientJ`: `cqjStep` iterated `N.primeFactorsList.length` times, ℓ = n.minFac each time."""
    E = curve(a, p)
    H = points_of_subgroup(E, [P])
    n = N
    for _ in range(int(pari.bigomega(N))):
        l = int(pari.factor(n)[0][0])
        a, E, H = step(a, E, H, l, p)
        n //= l
    c4, disc = E[9], E[11]
    return c4 ** 3 / disc


def main():
    random.seed(20261115)
    rows, n_ok = [], 0
    Ns = [2, 3, 4, 5, 6, 7, 8, 9, 10, 12]
    tests = 0
    while tests < 30:
        N = Ns[tests % len(Ns)]
        p = int(pari.nextprime(random.randint(200, 2000)))
        if p % N == 0 or p <= 3:
            continue
        a = [random.randrange(p) for _ in range(5)]
        try:
            E = curve(a, p)
        except cypari2.PariError:
            continue
        n = int(pari.ellcard(E))
        if n % N:
            continue
        G = pari.ellgenerators(E)
        # a point of exact order N
        P = None
        for g in G:
            og = int(pari.ellorder(E, g))
            if og % N == 0:
                P = pari.ellmul(E, g, og // N)
                break
        if P is None or int(pari.ellorder(E, P)) != N:
            continue
        jL = cyclic_quotient_j(list(a), P, N, p)
        Eiso = pari.ellisogeny(E, P, 1)
        jP = pari.ellinit(Eiso)[12]
        ok = (jL == jP)
        line = f'N={N} p={p} a={a} P={P} j(E)={E[12]} j_lean={jL} j_pari={jP} agree={ok}'
        if pari.isprime(N):
            phi = pari.polmodular(N)
            val = pari.substvec(phi, ['x', 'y'], [jL, E[12]])
            line += f' Phi_N(j_lean,j)={val}'
            ok = ok and val == 0
        rows.append(line)
        n_ok += ok
        tests += 1
    print('\n'.join(rows))
    print(f'{n_ok}/{tests} agree')


main()
