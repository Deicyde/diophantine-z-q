#!/usr/bin/env python3
"""leaf-fold8: generate the copied OneProof modules from the split tasks' committed files.

Run from the repository root.  Each module is a verbatim slice of its source with the imports replaced by
the module's own header, a banner docstring added, and the trailing `#print axioms` lines dropped.
`verbatim_check8.py` checks the result against the sources.

| module | source | slice |
|---|---|---|
| H/TailY   | scratch/height-glue/Rows.lean     | lines 10-2011 (height-split body, metrization2 kernel copy, first half) |
| H/TailZ   | scratch/height-glue/Rows.lean     | lines 2012-3506 (rest: unif-dims JacDescends, AUUnique, part_main, part_rows) |
| H/TailZ2  | scratch/qm-glue/HauptGlue.lean    | lines 2198-3687 (qm-split's Haupt.lean section; lines 1-2197 are leafq-check's Fold.lean, already in TailO) |
| H/TailZ3  | scratch/qm-glue/HauptGlue.lean    | lines 3688-end (qm-glue additions: GammaStarFromO1 proof, value 24, rows H-87/H-88) |
| TYZSplit  | scratch/tyz-split/T11.lean        | lines 2-end (row T-11 from the printed TYZ Theorem 3.3) |
"""
import re

ROWS = 'scratch/height-glue/Rows.lean'
HAUPT = 'scratch/qm-glue/HauptGlue.lean'
T11 = 'scratch/tyz-split/T11.lean'
OUT = 'ZInQKernel/OneProof/'


def lines(f):
    return open(f).read().split('\n')


def strip_prints(ls):
    return [l for l in ls if not l.startswith('#print')]


def write(path, header, body):
    while body and body[-1].strip() == '':
        body.pop()
    open(OUT + path, 'w').write('\n'.join(header + body) + '\n')


R = lines(ROWS)
assert R[1 - 1].startswith('import ZInQKernel.HDecomp.LeafPush2.R22')
assert R[2011 - 1] == 'end ZInQ.Metrization2', R[2010]
rows_imports = [l for l in R[:9] if l.startswith('import ')]

write('H/TailY.lean', rows_imports + ['', '''/-! # OneProof H, leaf-fold8 part 1: height-split and height-glue (first half)

`scratch/height-glue/Rows.lean` (tasks height-split and height-glue) lines 10-2011, verbatim: height-split's
`HeightSplit.lean` body (namespace `ZInQ.HeightSplit`: semistable reduction, the published stable height
`IsStableFaltingsHeight`, the leaves SS1-SS3, Bost, Javanpeykar, Faltings' Lemma 5, Pazuki, Gaudron-Rémond, and the
rows `R18`-`R22`, `StableHeightFinite` from them and the glue bundle `HeightGlue`), then the first half of
metrization2's kernel copy (`G0Dim`, `ZInQ.Metrization`, `ZInQ.Metrization2`). Imports only kernel modules.
Generated by `scratch/leaf-fold8/mk_modules.py`; `#print` lines dropped. -/
'''], R[9:2011])

write('H/TailZ.lean', ['import ZInQKernel.OneProof.H.TailY', '', '''/-! # OneProof H, leaf-fold8 part 2: height-split and height-glue (second half)

`scratch/height-glue/Rows.lean` lines 2012-3506, verbatim: the rest of metrization2's kernel copy, unif-dims'
`JacDetDescends` chain, height-glue's `AUUnique.lean`, `part_main.lean` and `part_rows.lean`: the four glue Props of
height-split's `HeightGlue` from T35 (`ZInQ.HeightGlue.heightGlue_of_t35`) and the six height rows from
height-split's leaves and T35 (`ZInQ.HeightGlue.heightRows_of_t35`). Generated by
`scratch/leaf-fold8/mk_modules.py`; `#print` lines dropped. -/
'''], strip_prints(R[2011:]))

H = lines(HAUPT)
assert H[2197 - 1] == 'end HDec.LeafQCheck.HM', H[2196]
assert 'QM-GLUE ADDITIONS' in H[3689 - 1], H[3688]
assert H[37 - 1] == 'set_option linter.all false'
write('H/TailZ2.lean', ['import ZInQKernel.OneProof.H.TailO', '', '''/-! # OneProof H, leaf-fold8 part 3: qm-split's `Haupt.lean` section (rows H-87, H-88)

`scratch/qm-glue/HauptGlue.lean` (task qm-glue) lines 2198-3687, verbatim: qm-split's section of `Haupt.lean`
(`QMHauptmodulBase3` from the valence formula, the elliptic-order divisibility, Shimizu's covolume). Lines 1-2197 of
`HauptGlue.lean` are leafq-check's `Fold.lean` (lines 1-934, 1326-2563), which is already in `TailO` (leaf-fold6
part f10; checked line by line by `verbatim_check8.py`), so this module imports `TailO` in their place. Generated
by `scratch/leaf-fold8/mk_modules.py`; `#print` lines dropped. -/

set_option linter.all false
'''], strip_prints(H[2197:3687]))

write('H/TailZ3.lean', ['import ZInQKernel.OneProof.H.TailZ2', '', '''/-! # OneProof H, leaf-fold8 part 4: qm-glue's additions (rows H-87, H-88 from published-form leaves)

`scratch/qm-glue/HauptGlue.lean` lines 3688-end, verbatim: `GammaStarFromO1` proved
(`HDec.LeafQCheck.QMglue.gammaStarFromO1_proof`), the CM value at discriminant `−24` reduced to Lin-Yang's
published Igusa vector (`Value24.IgusaCMValue24`), and the rows `valenceFormulaGammaStar_of_leaves` (H-87),
`qmHauptmodulBase3_of_leaves` (H-88). Generated by `scratch/leaf-fold8/mk_modules.py`; `#print` lines dropped. -/

set_option linter.all false
'''], strip_prints(H[3687:]))

T = lines(T11)
assert T[0] == 'import ZInQKernel.Contrib.TYZChain.Main'
write('TYZSplit.lean', ['import ZInQKernel.Contrib.TYZChain.Main', '', '''/-! # OneProof, leaf-fold8: tyz-split's row T-11

`scratch/tyz-split/T11.lean` (task tyz-split) lines 2-end, verbatim: `TYZ35.TYZThm33Pinned ℓ` for every `ℓ` with
`IsTYZLcal ℓ` from the printed form of Tian-Yuan-Zhang Theorem 3.3 (`TYZSplit.TYZThm33`,
`tyzThm33Pinned_of_tyzThm33`). Generated by `scratch/leaf-fold8/mk_modules.py`; `#print` lines dropped. -/
'''], strip_prints(T[1:]))

for m in ['H/TailY', 'H/TailZ', 'H/TailZ2', 'H/TailZ3', 'TYZSplit']:
    print(m, len(open(OUT + m + '.lean', 'rb').read()))
