#!/usr/bin/env python3
"""fold-b116 item 2: d2a6b (bypass; sga7_IX_3_5_ForwardGeom_Def34 -> elliotWildInertiaTrivial), regenerated on the
post-ss-faltings top, reproducible.

Run from the repository root of a head that has ss-faltings folded (OneProof/H/SSFChain.lean with
`sixContactMin_of_open73_sf`) and d2a6b merged (Contrib/OneProof/D2A6Wrap.lean, A6Z30.lean, D2WildNF.lean,
A6IntModel.lean). Steps (one Lean process at a time):

  1. lake build ZInQKernel.Contrib.OneProof.D2A6Wrap ZInQKernel.Contrib.OneProof.A6Z30
  2. lake env lean scratch/fold-b116/gen-d2a6b/TaintD.lean  > scratch/fold-b116/gen-d2a6b/taintD-out.txt
     lake env lean scratch/fold-b116/gen-d2a6b/TaintD2.lean > scratch/fold-b116/gen-d2a6b/taintD2-out.txt
  3. python3 scratch/fold-b116/fold_d2a6b.py
  4. lake build ZInQKernel.OneProof.H.D2A6Chain ZInQKernel.OneProof.H.TailZ<j> ZInQKernel.OneProof.Main ...

This script runs gen_chain.py (writing the chain directly to ZInQKernel/OneProof/H/D2A6Chain.lean: under
Contrib/OneProof #discharges reports every projection of the copied bundles as a self-match), removes d2a6b's
superseded chain Contrib/OneProof/D2A6Chain.lean (generated on TailZ80; same declaration names), runs gen_bypass.py
--mode post on the current Main top (numeric names OpenResearchLeaves<n+1> / sixContactMin_of_open<n+1>: autofold's
parser and gate.sh reject suffixed names), writes ZInQKernel/OneProof/H/TailZ<j>.lean (j = next free number), switches
Main (import, research bundle, top theorem, docstring paragraph) and replaces the kinds.tsv row of
sga7_IX_3_5_ForwardGeom_Def34 by the generated elliotWildInertiaTrivial row (claims.tsv has no row for either).
"""
import os, re, subprocess, sys

G = 'scratch/fold-b116/gen-d2a6b'
HD = 'ZInQKernel/OneProof/H'


def die(m):
    sys.exit('fold_d2a6b: ' + m)


def run(*a):
    subprocess.run([sys.executable, *a], check=True)


chain = f'{HD}/D2A6Chain.lean'
run(f'{G}/gen_chain.py', chain)
t = open(chain).read()
t = re.sub(r'\n#print axioms [^\n]*\n*$', '\n', t)
open(chain, 'w').write(t)
old_chain = 'ZInQKernel/Contrib/OneProof/D2A6Chain.lean'
if os.path.exists(old_chain):
    subprocess.run(['git', 'rm', '-q', old_chain], check=True)

# Main state before
mp = 'ZInQKernel/OneProof/Main.lean'
m = open(mp).read()
top_mod = re.search(r'^import ZInQKernel\.OneProof\.H\.(TailZ\d+)$', m, re.M).group(1)
R0 = re.search(r'\(r : HDec\.HSyn\.(\w+)\)', m).group(1)
OLD_TOP = re.search(r'HDec\.HSyn\.(sixContactMin_of_open\d+) r t l', m).group(1)
run(f'{G}/gen_bypass.py', '--mode', 'post', '--out', f'{G}/BypassFold.lean.txt', '--rows', f'{G}/kinds-rows.tsv')
text = open(f'{G}/BypassFold.lean.txt').read()
text = re.sub(r'\n#print axioms [^\n]*\n*$', '\n', text)
NEWR = re.search(r'^structure (OpenResearchLeaves\d+) : Prop where', text, re.M).group(1)
NEW_TOP = re.search(r'^theorem (sixContactMin_of_open\d+) ', text, re.M).group(1)
nums = [int(x.group(1)) for f in os.listdir(HD) if (x := re.fullmatch(r'TailZ(\d+)\.lean', f))]
j = max(nums) + 1
open(f'{HD}/TailZ{j}.lean', 'w').write(text)

m = m.replace(f'import ZInQKernel.OneProof.H.{top_mod}\n', f'import ZInQKernel.OneProof.H.TailZ{j}\n', 1)
for a, b in [(f'(r : HDec.HSyn.{R0})', f'(r : HDec.HSyn.{NEWR})'),
             (f'(HDec.HSyn.{OLD_TOP} r t l)', f'(HDec.HSyn.{NEW_TOP} r t l)')]:
    if a not in m:
        die(f'Main lacks {a}')
    m = m.replace(a, b, 1)
para = (
    f'd2a6b (folded by fold-b116, chain and bypass regenerated on the post-ss-faltings top) replaced the research field\n'
    f'`sga7_IX_3_5_ForwardGeom_Def34` (SGA 7 IX 3.5, not in the manuscript\'s bibliography) by `elliotWildInertiaTrivial`\n'
    f'(the manuscript\'s uncited sentence L817-818); D2 now goes through Raynaud\'s criterion as cited at L816\n'
    f'(`silverbergZarhinThm35`), and A6 and the kernel field\'s good reduction (L529-530) through the model of `Y₃` over\n'
    f'ℤ[1/30] (`y3FullThreeRepZ30`; `Contrib/OneProof/A6Z30.lean`, `D2A6Wrap.lean`). `{NEWR}` (`TailZ{j}`) is `{R0}`\n'
    f'with the field replaced, and `HDec.HSyn.{NEW_TOP}` goes through `sixContactMin_of_open73_sf_u`, a copy of the\n'
    f'chain of declarations of `sixContactMin_of_open73_sf` (ss-faltings\' chain) that carry the field\n'
    f'(`OneProof/H/D2A6Chain.lean`, generated by `scratch/fold-b116/gen-d2a6b/gen_chain.py`; bypass); no existing\n'
    f'declaration is changed. No SGA 7 statement remains a field.\n\n')
anchor = 'The hypotheses of `frozenTarget` are therefore exactly the open statements.'
if anchor not in m:
    die('Main docstring anchor missing')
m = m.replace(anchor, para + anchor, 1)
open(mp, 'w').write(m)

kp = 'docs/one-proof/kinds.tsv'
rows = open(kp).read().split('\n')
new = open(f'{G}/kinds-rows.tsv').read().rstrip('\n').split('\n')[1:]
if len(new) != 1 or new[0].split('\t')[1] != 'elliotWildInertiaTrivial':
    die('kinds-rows.tsv: expected the one elliotWildInertiaTrivial row')
hits = [i for i, r in enumerate(rows) if r.split('\t')[1:2] == ['sga7_IX_3_5_ForwardGeom_Def34']]
if len(hits) != 1:
    die('kinds.tsv: expected one sga7_IX_3_5_ForwardGeom_Def34 row')
rows[hits[0]] = new[0]
open(kp, 'w').write('\n'.join(rows))
print(f'wrote {chain}, {HD}/TailZ{j}.lean; Main -> {NEW_TOP} on {NEWR}; kinds row replaced')
