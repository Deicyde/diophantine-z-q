#!/usr/bin/env python3
"""Generate the modules ZInQKernel/Contrib/HeightBC/*.lean (task heightbc-contrib).

Run from the repository root.  Every module is a header (imports, module docstring with
provenance) + at most a few context lines re-opening the namespace that the source file had open
at the cut point + a VERBATIM slice of a scratch source (`#print` lines dropped) + at most an
`end <namespace>` line.  The slices are those that scratch/hodge-bc2/assemble_h5.py concatenates
into scratch/hodge-bc2/IntegrationH5.lean, with two replacements:
  * h5-glue's Part 1 (a copy of hodge-lattice §1-§5, H5Final.lean lines 20-712) is replaced by
    `import ZInQKernel.HDecomp.Faltings.HodgeLattice` (the kernel's adoption of the same text;
    `diff` shows only re-wrapped lines), so no declaration is duplicated;
  * hodge-bc2's ExtFrac body is replaced by `import ZInQKernel.Contrib.HodgeBC2.ExtFrac`.
`Main.lean` (last) also contains new code: the theorems with the kernel's Props as types.
"""
import re, os

D = 'ZInQKernel/Contrib/HeightBC/'
MOD = 'ZInQKernel.Contrib.HeightBC.'


def rd(p):
    return open(p).read()


def lines(p):
    return rd(p).split('\n')


def noprint(s):
    return '\n'.join(l for l in s.split('\n') if not l.startswith('#print'))


def L(src, a, b):
    """Lines a..b (1-indexed, inclusive) of src."""
    return '\n'.join(lines(src)[a - 1:b])


HDR = '''/-!
# Height base change, {n}: {title}

Copyright: this file is part of the fork Deicyde/diophantine-z-q (task heightbc-contrib,
2026-11-13). Generated by `scratch/heightbc-contrib/build_modules.py`.

{body}
-/
'''

STALK_CTX = 'universe u\n\nopen CategoryTheory Limits\n'
FIN = 'scratch/height-bc/Final.lean'
H5 = 'scratch/h5-glue/H5Final.lean'
HB_OPENS = L(FIN, 29, 33) + '\n'  # namespace ZInQ.HeightBC + its three `open` lines
H5_CTX = L(H5, 716, 730) + '\n'    # set_option, namespace ZInQ.H5Glue, opens, variable

# sanity checks on the cut points
fin = lines(FIN)
assert fin[0] == 'import ZInQKernel.HDecomp.Faltings.Leaves'
assert fin[28] == 'namespace ZInQ.HeightBC' and fin[32] == 'open PkgI3 (AbVar)'
assert fin[589] == '' and fin[590].startswith('/-! # Part B'), fin[590]
assert fin[1442] == 'end GermDer' and fin[1444].startswith('/-! # Part C'), fin[1444]
assert fin[2100] == 'end ZInQ.HeightBC'
h5 = lines(H5)
assert h5[711] == 'end ZInQ.DefFaltings.HodgeLattice'
assert h5[715] == 'set_option linter.style.haveILetI false' and h5[717] == 'namespace ZInQ.H5Glue'
assert h5[729].startswith('variable {K : Type}') and h5[730] == ''
assert h5[1730] == '' and h5[1731] == '/-! ## Part 3 -/', h5[1731]
assert h5[2358] == '' and h5[2359].startswith('/-! ## Part 4'), h5[2359]
assert h5[2626] == 'end ZInQ.H5Glue'
sp = rd('scratch/infra-stalks/StalkPullback.lean')
sp_body = sp[sp.index('universe u'):]
pe = rd('scratch/height-bc/PartE.lean.part').split('%%MAINPART%%')
assert len(pe) == 2

modules = []  # (name, imports, title, provenance, text)


def add(name, imports, title, prov, text):
    modules.append((name, imports, title, prov, text))


add('StalkPullback', ['Mathlib'], 'stalks of fibre products (Mathlib-only)',
    'VERBATIM: `scratch/infra-stalks/StalkPullback.lean` (task infra-stalks) from `universe u` to\n'
    'the end (its module docstring is reproduced below).',
    L('scratch/infra-stalks/StalkPullback.lean', 3, 18) + '\n\n' + sp_body)

add('LocalStructure', [MOD + 'StalkPullback'],
    'local structure of a fibre product at field-valued points (Mathlib-only)',
    'VERBATIM: `scratch/infra-stalks/local_structure.lean.part` (task infra-stalks), `#print` lines\n'
    'dropped, after the context lines `universe u` and `open CategoryTheory Limits` (top level of\n'
    '`StalkPullback.lean`, which precedes this part in infra-stalks\' assembled files).',
    STALK_CTX + '\n' + noprint(rd('scratch/infra-stalks/local_structure.lean.part')))

add('StalkTensor', [MOD + 'StalkPullback'],
    'the stalk of a fibre product is a localization of the tensor product (Mathlib-only)',
    'VERBATIM: `scratch/infra-stalks/stalk_tensor.lean.part` (task infra-stalks), `#print` lines\n'
    'dropped, after the context lines `universe u` and `open CategoryTheory Limits`.',
    STALK_CTX + '\n' + noprint(rd('scratch/infra-stalks/stalk_tensor.lean.part')))

add('CotangentBC', [MOD + 'StalkTensor'],
    'cotangent space of a base change by a field extension (Mathlib-only)',
    'VERBATIM: `scratch/infra-stalks/cot_bc.lean.part` (task infra-stalks), `#print` lines dropped,\n'
    'after the context lines `universe u` and `open CategoryTheory Limits`.',
    STALK_CTX + '\n' + noprint(rd('scratch/infra-stalks/cot_bc.lean.part')))

add('Copies', ['ZInQKernel.HDecomp.Faltings.Leaves', 'Mathlib'],
    'statements of height-bc and the Arakelov half of H4a',
    'VERBATIM: lines 3-589 of `scratch/height-bc/Final.lean` (task height-bc): its module docstring,\n'
    'its verbatim copies (`IsBaseChangeOf`, `ModelHeightBaseChange`, `HodgeLineBaseChange`, ...) and\n'
    'Part A; then `end ZInQ.HeightBC`. The copy `ZInQ.HeightBC.ModelHeightBaseChange` is the kernel\'s\n'
    '`ZInQ.H5Neron.ModelHeightBaseChange` up to the copied `IsBaseChangeOf`\n'
    '(`Main.lean`: `heightBC_modelHeightBaseChange_iff`, `Iff.rfl`).',
    L(FIN, 3, 589) + '\n\nend ZInQ.HeightBC\n')

add('Natural', [MOD + 'Copies'],
    'the natural map of a base change (height-bc Part B)',
    'VERBATIM: lines 591-1443 of `scratch/height-bc/Final.lean` (Part B), between its lines 29-33\n'
    '(`namespace ZInQ.HeightBC` and its `open` lines) and `end ZInQ.HeightBC`.',
    HB_OPENS + '\n' + L(FIN, 591, 1443) + '\n\nend ZInQ.HeightBC\n')

add('GlueC', [MOD + 'Natural'],
    'glue statements over the natural map (height-bc Part C)',
    'VERBATIM: lines 1445-2101 of `scratch/height-bc/Final.lean` (Part C, with the statements\n'
    '`OmegaBaseChange`, `HodgeBCInjective`, `CotangentSpanBC`, `UniformizationLiftAnalytic` and the\n'
    'reductions `modelHeightBaseChange_of_glue4`, `hodgeLineBaseChange_of_glue4`), after its lines\n'
    '29-33.',
    HB_OPENS + '\n' + L(FIN, 1445, 2101) + '\n')

add('CotangentSpan', [MOD + 'GlueC', MOD + 'StalkPullback'],
    '`CotangentSpanBC` (infra-stalks)',
    'VERBATIM: `scratch/infra-stalks/bc_proof.lean.part` (task infra-stalks), `#print` lines dropped,\n'
    'after the context lines that `scratch/infra-stalks/assemble_hbc.py` puts before it\n'
    '(`namespace ZInQ.HeightBC` and its `open` lines).',
    'namespace ZInQ.HeightBC\n\nopen CategoryTheory AlgebraicGeometry Limits MonoidalCategory '
    'CartesianMonoidalCategory MonObj\nopen NumberField DefFaltings\nopen PkgI3 (AbVar)\n\n'
    + noprint(rd('scratch/infra-stalks/bc_proof.lean.part')))

add('UniformizationLift', [MOD + 'GlueC', MOD + 'LocalStructure'],
    '`UniformizationLiftAnalytic` (infra-stalks)',
    'VERBATIM: `scratch/infra-stalks/ula_proof.lean.part` (task infra-stalks), `#print` lines dropped.',
    noprint(rd('scratch/infra-stalks/ula_proof.lean.part')))

add('HodgeBCInjective', [MOD + 'CotangentSpan', MOD + 'CotangentBC',
                         'ZInQKernel.Contrib.HodgeBC2.ExtFrac'],
    '`HodgeBCInjective` (hodge-bc2)',
    'VERBATIM: `scratch/hodge-bc2/hbc_proof.lean.part` (task hodge-bc2), `#print` lines dropped.',
    noprint(rd('scratch/hodge-bc2/hbc_proof.lean.part')))

add('OmegaBC', [MOD + 'HodgeBCInjective'],
    '`OmegaLocalization` and `OmegaBaseChange` (hodge-bc2)',
    'VERBATIM: `scratch/hodge-bc2/omega_proof.lean.part` (task hodge-bc2), `#print` lines dropped.',
    noprint(rd('scratch/hodge-bc2/omega_proof.lean.part')))

add('G0StableBC', ['ZInQKernel.HDecomp.Faltings.Leaves', 'Mathlib'],
    'g0-stablebc: `StableHeightBaseChange` from `HodgeLineBaseChange`',
    'VERBATIM: the alias part of `scratch/height-bc/PartE.lean.part` (task height-bc:\n'
    '`ZInQ.DefFaltings.AbVar := PkgI3.AbVar`, the name g0-split\'s statement uses) followed by\n'
    '`scratch/g0-stablebc/Main.part` (task g0-stablebc), `#print` lines dropped.',
    pe[0] + noprint(rd('scratch/g0-stablebc/Main.part')))

H5DOC = L(H5, 3, 18)
add('H5GlueMinimal', ['ZInQKernel.HDecomp.Faltings.HodgeLattice',
                      'ZInQKernel.HDecomp.Faltings.Leaves', 'Mathlib'],
    'h5-glue Part 2: `HeightAntitone`, `NeronModelMinimal`',
    'VERBATIM: lines 714-1731 of `scratch/h5-glue/H5Final.lean` (task h5-glue, Part 2), then\n'
    '`end ZInQ.H5Glue`. Its Part 1 (lines 20-712, a copy of hodge-lattice §1-§5) is the kernel\'s\n'
    '`ZInQKernel/HDecomp/Faltings/HodgeLattice.lean` (same text up to line wrapping), imported\n'
    'instead. h5-glue\'s module docstring (lines 3-18) follows.',
    H5DOC + '\n\n' + L(H5, 714, 1731) + '\nend ZInQ.H5Glue\n')

add('H5GlueReduction', [MOD + 'H5GlueMinimal'],
    'h5-glue Part 3: base change, open subgroups, the reduction of H5, additivity',
    'VERBATIM: lines 1732-2358 of `scratch/h5-glue/H5Final.lean` (Part 3), after its lines 716-730\n'
    '(`set_option`, `namespace ZInQ.H5Glue`, `open` lines, `variable` line), then\n'
    '`end ZInQ.H5Glue`.',
    H5_CTX + '\n' + L(H5, 1732, 2358) + '\nend ZInQ.H5Glue\n')

add('H5GlueOpen', [MOD + 'H5GlueReduction'],
    'h5-glue Part 4: `OpenImmersionHeightLe`, `OpenSubgroupHeight`',
    'VERBATIM: lines 2359-2627 of `scratch/h5-glue/H5Final.lean` (Part 4), after its lines 716-730.',
    H5_CTX + '\n' + L(H5, 2359, 2627) + '\n')

MAIN_NEW = rd('scratch/heightbc-contrib/main_new.lean.part')
add('Main', [MOD + 'UniformizationLift', MOD + 'OmegaBC', MOD + 'G0StableBC',
             MOD + 'H5GlueOpen', 'ZInQKernel.HDecomp.Faltings.H5BaseChange'],
    'the closed theorems',
    'Parts 1-4 VERBATIM, `#print` lines dropped: `scratch/infra-stalks/hbc_final.lean.part`\n'
    '(infra-stalks), the tail of `scratch/height-bc/PartE.lean.part` (height-bc),\n'
    '`scratch/hodge-bc2/int_final.lean.part` and `int_h5.lean.part` (hodge-bc2).\n'
    'Part 5 (new, `scratch/heightbc-contrib/main_new.lean.part`): the theorems whose types are the\n'
    'kernel\'s Props `ZInQ.H5Neron.ModelHeightBaseChange`, `ZInQ.H5Neron.OpenSubgroupHeight`,\n'
    '`ZInQ.DefFaltings.NeronModelMinimal`, and H5 from the kernel\'s leaves N1, N2 alone.',
    noprint(rd('scratch/infra-stalks/hbc_final.lean.part')) + '\n' + noprint(pe[1]) + '\n'
    + noprint(rd('scratch/hodge-bc2/int_final.lean.part')) + '\n'
    + noprint(rd('scratch/hodge-bc2/int_h5.lean.part')) + '\n' + MAIN_NEW)

os.makedirs(D, exist_ok=True)
for i, (name, imps, title, prov, text) in enumerate(modules, 1):
    out = '\n'.join('import ' + m for m in imps) + '\n\n' + HDR.format(n=['I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII', 'XIII', 'XIV', 'XV', 'XVI', 'XVII'][i - 1], title=title, body=prov) + '\n' + text.rstrip('\n') + '\n'
    assert 'sorry' not in re.sub(r'--.*|/-.*?-/', '', out, flags=re.S), name
    open(D + name + '.lean', 'w').write(out)
    print(name, len(out.split('\n')))
