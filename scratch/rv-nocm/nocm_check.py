def sqfree(q):
    """squarefree representative of the rational q modulo squares"""
    q = Fr(q)
    return core_int(q.numerator * q.denominator)


def fund(D):
    dK = coredisc(D)
    f = isqrt(D // dK)
    assert f * f * dK == D
    return dK, f


def bvalue(dK):
    return sum(1 for p in (2, 3) if kron(dK, p) == -1)


def qdisc(a):
    """discriminant of Q(sqrt a), a squarefree != 1"""
    return a if a % 4 == 1 else 4 * a


def span(gens):
    """subgroup of Q^*/Q^*2 generated by squarefree gens, as a set of squarefree ints"""
    S = {1}
    for g in gens:
        S |= {core_int(s * g) for s in S}
    return S


