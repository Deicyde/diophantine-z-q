def small_primes(n):
    s = bytearray([1]) * (n + 1); s[0:2] = b"\x00\x00"
    for i in range(2, isqrt(n) + 1):
        if s[i]:
            s[i * i::i] = bytearray(len(s[i * i::i]))
    return [i for i in range(n + 1) if s[i]]


PR = small_primes(2 * 10**6)


def is_probable_prime(n):
    if n < 2:
        return False
    for p in PR[:20]:
        if n % p == 0:
            return n == p
    d, r = n - 1, 0
    while d % 2 == 0:
        d //= 2; r += 1
    for a in PR[:20]:
        x = pow(a, d, n)
        if x in (1, n - 1):
            continue
        for _ in range(r - 1):
            x = x * x % n
            if x == n - 1:
                break
        else:
            return False
    return True


def core_int(n):
    """squarefree part (with sign) of a nonzero integer; raises if a cofactor is undecided"""
    sign = -1 if n < 0 else 1
    n = abs(n); c = 1
    for p in PR:
        if p * p > n:
            break
        if n % p == 0:
            e = 0
            while n % p == 0:
                n //= p; e += 1
            if e % 2:
                c *= p
    if n > 1:
        r = isqrt(n)
        if r * r == n:
            pass
        elif is_probable_prime(n):
            c *= n
        else:
            raise ValueError("undecided cofactor %d" % n)
    return sign * c


def kron(d, p):
    if p == 2:
        if d % 2 == 0:
            return 0
        return 1 if d % 8 in (1, 7) else -1
    if d % p == 0:
        return 0
    return 1 if pow(d % p, (p - 1) // 2, p) == 1 else -1


def classno(D):
    """number of primitive reduced forms of discriminant D < 0"""
    h = 0; a = 1
    while 3 * a * a <= -D:
        for b in range(-a + 1, a + 1):
            if (b * b - D) % (4 * a):
                continue
            c = (b * b - D) // (4 * a)
            if c < a or (c == a and b < 0):
                continue
            if gcd(gcd(a, abs(b)), c) != 1:
                continue
            h += 1
        a += 1
    return h


def coredisc(D):
    s = core_int(D)
    return s if s % 4 == 1 else 4 * s


