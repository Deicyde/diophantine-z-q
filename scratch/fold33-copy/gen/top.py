def struct_fields(path, name):
    s = open(path).read()
    m = re.search(r"^structure " + name + r" : Prop where\n((?:  .*\n)+)", s, re.M)
    assert m, (path, name)
    body = "".join(l for l in m.group(1).splitlines(keepends=True) if not l.lstrip().startswith("-- "))
    names = re.findall(r"^  (\w+) :", body, re.M)
    return body, names


def patch_main(subs):
    p = "ZInQKernel/OneProof/Main.lean"
    s = open(p).read()
    for old, new in subs:
        if s.count(old) != 1:
            raise SystemExit("Main: " + old)
        s = s.replace(old, new)
    open(p, "w").write(s)


