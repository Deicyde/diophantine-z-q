# Exact check: Galois action on the Weierstrass points of the genus-2 curve C with
# (Jac C, theta) = (A, lambda), A a QM surface with O = Z<1,i,(1+j)/2,(i+ij)/2> in B=(2,-3) acting over K.
# G_K acts on A[2] = O/2O (free rank-1 left O/2O-module) by right multiplication by units u of O/2O.
# Weierstrass points <-> odd quadratic forms q on A[2] refining e_2(x,y) = Trd(mu^-1 x ybar) mod 2 (Mumford).
from fractions import Fraction as Fr
from itertools import product
# quaternion (a,b,c,d) = a + b i + c j + d ij, i^2=2, j^2=-3, ij=-ji
A_, B_ = 2, -3
def mul(x, y):
    a1,b1,c1,d1 = x; a2,b2,c2,d2 = y
    return (a1*a2 + A_*b1*b2 + B_*c1*c2 - A_*B_*d1*d2,
            a1*b2 + b1*a2 - B_*c1*d2 + B_*d1*c2,
            a1*c2 + c1*a2 + A_*b1*d2 - A_*d1*b2,
            a1*d2 + d1*a2 + b1*c2 - c1*b2)
def conj(x): a,b,c,d = x; return (a,-b,-c,-d)
def trd(x): return 2*x[0]
def nrd(x): return mul(x,conj(x))[0]
H = Fr(1,2)
basis = [(1,0,0,0),(0,1,0,0),(H,0,H,0),(0,H,0,H)]
mu = (0,0,2,1)
n = nrd(mu); muinv = tuple(Fr(t)/n for t in conj(mu))
assert mul(mu,mu) == (-6,0,0,0)
def vec(coeffs): return tuple(sum(Fr(c)*b[k] for c,b in zip(coeffs,basis)) for k in range(4))
# coordinates in the basis: solve
import sympy
Bm = sympy.Matrix([[sympy.Rational(b[k]) for b in basis] for k in range(4)])
Binv = Bm.inv()
def coords(x):
    v = Binv*sympy.Matrix([sympy.Rational(t) for t in x]); assert all(t.is_integer for t in v), x
    return tuple(int(t) for t in v)
def E(x,y): return trd(mul(mul(muinv,x),conj(y)))
G = [[E(b1,b2) for b2 in basis] for b1 in basis]
print("Gram", G, "det", sympy.Matrix(G).det())
els = list(product(range(2),repeat=4))   # O/2O
def e2(v,w): return int(sum(v[a]*w[b]*G[a][b] for a in range(4) for b in range(4))) % 2
# units of O/2O: elements with odd reduced norm
def nrd_c(v): return nrd(vec(v))
units = [v for v in els if int(nrd_c(v)) % 2 == 1]
print("#units of O/2O:", len(units))
def rmul(v,u):  # v*u mod 2 in coordinates
    return tuple(c % 2 for c in coords(mul(vec(v),vec(u))))
# check right multiplication preserves e2
for u in units:
    for v in els:
        for w in els:
            assert e2(rmul(v,u),rmul(w,u)) == e2(v,w)
print("right multiplication by units preserves e_2: True")
# quadratic forms refining e2: q(v)= sum q_a v_a + sum_{a<b} G[a][b] v_a v_b (mod 2), determined by values on basis
def qform(qb):
    def q(v): return (sum(qb[a]*v[a] for a in range(4)) + sum(G[a][b]*v[a]*v[b] for a in range(4) for b in range(a+1,4))) % 2
    return q
forms = []
for qb in product(range(2),repeat=4):
    q = qform(qb); vals = tuple(q(v) for v in els)
    arf = 1 if sum(vals) > 8 else 0   # odd form has 10 ones (6 zeros)
    forms.append((vals, arf))
odd = [f for f in forms if f[1] == 1]; even = [f for f in forms if f[1] == 0]
print("#odd forms (Weierstrass points):", len(odd), "#even:", len(even))
idx = {v:k for k,v in enumerate(els)}
def act(u, vals):  # (u q)(v) = q(v u)  (right action; orbit structure same)
    return tuple(vals[idx[rmul(v,u)]] for v in els)
oddset = [f[0] for f in odd]
# orbits of the full unit group
def orbits(group):
    seen=set(); orbs=[]
    for f in oddset:
        if f in seen: continue
        orb={act(u,f) for u in group}; seen|=orb; orbs.append(len(orb))
    return sorted(orbs)
print("orbits of (O/2O)^* on Weierstrass points:", orbits(units))
# group structure: element orders, and all subgroups' orbit types
def mulc(u,v): return rmul(u,v)
one=(1,0,0,0)
def order(u):
    k=1; x=u
    while x!=one: x=mulc(x,u); k+=1
    return k
print("element orders:", sorted(order(u) for u in units))
# enumerate subgroups generated by <=2 elements
subs=set()
for u in units:
    for v in units:
        S={one}; frontier=[one]
        while frontier:
            x=frontier.pop()
            for g in (u,v):
                y=mulc(x,g)
                if y not in S: S.add(y); frontier.append(y)
        subs.add(frozenset(S))
for S in sorted(subs,key=len):
    print("subgroup of order",len(S),"orbits",orbits(S))
