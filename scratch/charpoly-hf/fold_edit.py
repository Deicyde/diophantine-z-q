#!/usr/bin/env python3
"""charpoly-hf fold: replace the open field `charPolyIndepOfEllAlgClosed` (Mumford §19 Thm 4) by
`homFreeFiniteAlgClosedCharP` (Mumford §19 Thm 3, characteristic p) on leaf-fold33b's route.

Count-neutral swap (one published LEAF for another); see docs/research/charpoly-hf.md §5.

Edits (every match is asserted):
* ZInQKernel/Contrib/OneProof/HomFreeFiniteAlgClosedReroute.lean (homfree-noemb's copies, the only place where the
  field is read on the route, scratch/charpoly-hf/taint_out.txt):
  - imports MinpolyIndepCharPThm3 and R16PrintedC;
  - `t7` of TextbookLeavesHF, OpenTextbookLeaves2HF-4HF retyped `PkgI3.CharPolyIndepOfEll` ->
    `CharpolyHF.MinpolyIndepOfEllCharP`;
  - gluePieces_of_open4_hf: `linkedTateData_of_local t.t7` -> `linkedTateData_of_local_minpolyCharP t.t7
    (tateModuleFree_of_t5' t.t5)`;
  - textbookLeaves4_of_open6_hf: `t7 := t7_of_algClosed5 t.charPolyIndepOfEllAlgClosed` ->
    `t7 := minpolyIndepOfEllCharP_of_homFree t.homFreeFiniteAlgClosedCharP (tateModuleFree_of_t5' (torsionStructure_ofK5 t.t5))`;
  - OpenTextbookLeaves6HF-14HF: field `charPolyIndepOfEllAlgClosed : AVB1.CharPolyIndepOfEllAlgClosed` ->
    `homFreeFiniteAlgClosedCharP : CharpolyHF.HomFreeFiniteAlgClosedCharP`, pass-through lines renamed;
  - openResearchLeaves21_of_OpenResearchLeaves22_hf: `r16_of_printed n.r16CoreY t.mumfordTorsionAlgClosed
    t.charPolyIndepOfEllAlgClosed` -> `r16_of_printedC n.r16CoreY uniformizationLeafAll_proof t.mumfordTorsionAlgClosed`.
* ZInQKernel/OneProof/H/TailZ48.lean: OpenTextbookLeaves15's field and its pass-through renamed/retyped the same way.

The original OpenTextbookLeaves13 (named by the blueprint) and every other existing declaration name are kept.
Usage: python3 fold_edit.py --tree <repo root>
"""
import argparse
import pathlib
import re

ap = argparse.ArgumentParser()
ap.add_argument('--tree', required=True)
args = ap.parse_args()
root = pathlib.Path(args.tree)

NEWT = '_root_.ZInQ.Contrib.OneProof.CharpolyHF.HomFreeFiniteAlgClosedCharP'
MINP = '_root_.ZInQ.Contrib.OneProof.CharpolyHF.MinpolyIndepOfEllCharP'


def sub(s, old, new, count):
    n = s.count(old)
    assert n == count, f'expected {count} matches of {old!r}, found {n}'
    return s.replace(old, new)


# --- the reroute copies -------------------------------------------------------------------------------------------
p = root / 'ZInQKernel/Contrib/OneProof/HomFreeFiniteAlgClosedReroute.lean'
s = p.read_text()
s = sub(s, 'import ZInQKernel.Contrib.OneProof.HomFreeFiniteAlgClosedReroute.Consumers\n',
        'import ZInQKernel.Contrib.OneProof.HomFreeFiniteAlgClosedReroute.Consumers\n'
        'import ZInQKernel.Contrib.OneProof.MinpolyIndepCharPThm3\n'
        'import ZInQKernel.Contrib.OneProof.R16PrintedC\n', 1)
s = sub(s, 'without `homFreeFiniteAlgClosed`. No new leaf. Generated by `scratch/homfree-noemb/gen/gen.py`. -/\n',
        'without `homFreeFiniteAlgClosed`. No new leaf. Generated by `scratch/homfree-noemb/gen/gen.py`.\n\n'
        'charpoly-hf (hand edit after generation, `scratch/charpoly-hf/fold_edit.py`): the T7 field\n'
        '`charPolyIndepOfEllAlgClosed` (Mumford §19 Thm 4) is replaced by `homFreeFiniteAlgClosedCharP` (Mumford §19\n'
        'Thm 3 in characteristic `p`). `t7` is retyped `CharpolyHF.MinpolyIndepOfEllCharP` (supplied by\n'
        '`minpolyIndepOfEllCharP_of_homFree`), `gluePieces_of_open4_hf` uses charpoly-charp\'s reroute of\n'
        '`common_trace` in the form `linkedTateData_of_local_minpolyCharP`, and R16 reads T7 only at `ℚ`\n'
        '(`R16Split.r16_of_printedC`). -/\n', 1)
s = sub(s, '  t7 : PkgI3.CharPolyIndepOfEll\n', f'  t7 : {MINP}\n', 4)
s = sub(s, '(G0AssembleMod.linkedTateData_of_local t.t7\n',
        "(G0AssembleMod.linkedTateData_of_local_minpolyCharP t.t7 (tateModuleFree_of_t5' t.t5)\n", 1)
s = sub(s, '  t7 := t7_of_algClosed5 t.charPolyIndepOfEllAlgClosed\n',
        '  t7 := _root_.ZInQ.Contrib.OneProof.CharpolyHF.minpolyIndepOfEllCharP_of_homFree '
        "t.homFreeFiniteAlgClosedCharP (tateModuleFree_of_t5' (torsionStructure_ofK5 t.t5))\n", 1)
s = sub(s, '  /-- av-b1, LEAF: Mumford §19 Thm 4 (consequence) over an algebraically closed field. -/\n'
           '  charPolyIndepOfEllAlgClosed : _root_.ZInQ.Contrib.AVB1.CharPolyIndepOfEllAlgClosed\n',
        '  /-- charpoly-hf, LEAF: Mumford §19 Thm 3 over an algebraically closed field of characteristic `p`. -/\n'
        f'  homFreeFiniteAlgClosedCharP : {NEWT}\n', 1)
s = sub(s, '  charPolyIndepOfEllAlgClosed : _root_.ZInQ.Contrib.AVB1.CharPolyIndepOfEllAlgClosed\n',
        f'  homFreeFiniteAlgClosedCharP : {NEWT}\n', 8)
s = sub(s, '  charPolyIndepOfEllAlgClosed := t.charPolyIndepOfEllAlgClosed\n',
        '  homFreeFiniteAlgClosedCharP := t.homFreeFiniteAlgClosedCharP\n', 4)
s = sub(s, '  charPolyIndepOfEllAlgClosed := n.charPolyIndepOfEllAlgClosed\n',
        '  homFreeFiniteAlgClosedCharP := n.homFreeFiniteAlgClosedCharP\n', 4)
s = sub(s, '  r16 := _root_.R16Split.r16_of_printed n.r16CoreY t.mumfordTorsionAlgClosed t.charPolyIndepOfEllAlgClosed\n',
        '  r16 := _root_.R16Split.r16_of_printedC n.r16CoreY _root_.uniformizationLeafAll_proof t.mumfordTorsionAlgClosed\n',
        1)
code = re.sub(r'/-.*?-/', '', s, flags=re.S)
code = '\n'.join(l for l in code.splitlines() if not l.lstrip().startswith('--'))
assert 'charPolyIndepOfEllAlgClosed' not in code and 'CharPolyIndepOfEll' not in code and 't7_of_algClosed5' not in code
p.write_text(s)

# --- TailZ48 -----------------------------------------------------------------------------------------------------
p = root / 'ZInQKernel/OneProof/H/TailZ48.lean'
s = p.read_text()
s = sub(s, '  charPolyIndepOfEllAlgClosed : _root_.ZInQ.Contrib.AVB1.CharPolyIndepOfEllAlgClosed\n',
        f'  homFreeFiniteAlgClosedCharP : {NEWT}\n', 1)
s = sub(s, '  charPolyIndepOfEllAlgClosed := n.charPolyIndepOfEllAlgClosed\n',
        '  homFreeFiniteAlgClosedCharP := n.homFreeFiniteAlgClosedCharP\n', 1)
s = sub(s, '/-- `OpenTextbookLeaves14` without `homFreeFiniteAlgClosed` (leaf-fold33, homfree-noemb). -/\n',
        '/-- `OpenTextbookLeaves14` without `homFreeFiniteAlgClosed` (leaf-fold33, homfree-noemb), and with\n'
        '`charPolyIndepOfEllAlgClosed` (Mumford §19 Thm 4) replaced by `homFreeFiniteAlgClosedCharP` (Mumford §19 Thm 3\n'
        'in characteristic `p`; charpoly-hf). -/\n', 1)
assert 'charPolyIndepOfEllAlgClosed :' not in s
p.write_text(s)
print('fold_edit: OK')
