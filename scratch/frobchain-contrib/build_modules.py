#!/usr/bin/env python3
"""Generate the modules ZInQKernel/Contrib/FrobChain/*.lean (task frobchain-contrib).

Run from the repository root.  Every module is a header (imports, a module docstring with the
provenance) + at most a few context lines + VERBATIM slices of scratch sources (`#print` lines
dropped) + at most closing `end` lines.  The slices are, in order, exactly the pieces that
scratch/linked-frob/assemble.sh appends (its "AFR block" and parts), i.e. the order of
frob-pieces' FrobPiecesFull.lean, with three replacements:
  * the absolute Frobenius (afr-absfrob's `AbsFrobDef.lean`) is not copied: it is imported from
    task frob-contrib's adoption `ZInQKernel.Contrib.AbsFrob.AlgFrobRed`, and alg-frob-red's copy
    of `def AbsFrob` (cmp-identical to frob-contrib's, checked below) is dropped from part_red;
  * linked-tate's environment (scratch/h-decomposition/Leaves.lean + 29 parts) is not copied: the
    statement `UnramTate.LinkedFrob` and the definition `tmOf` it uses are slices of
    linked-tate's part 97, and the one further definition it uses, g14-trace's
    `G14Trace.FrobTraceLink`, is a slice of scratch/g14-trace/part_g14.lean;
  * `linkedFrob_of_textbook` (linked-frob part 20; it takes Leaves.lean's bundle
    `HSyn.TextbookLeaves`, which has no kernel counterpart) is not copied.
`Main.lean` (last) also contains new code: the closed reductions in namespace
`ZInQ.Contrib.FrobChain` and the `Iff.rfl` checks of copies.
"""
import os

D = 'ZInQKernel/Contrib/FrobChain/'
MOD = 'ZInQKernel.Contrib.FrobChain.'


def rd(p):
    return open(p).read()


def lines(p):
    return rd(p).split('\n')


def noprint(s):
    return '\n'.join(l for l in s.split('\n') if not l.startswith('#print'))


def L(src, a, b=None):
    """Lines a..b (1-indexed, inclusive; b=None: to the end) of src."""
    ls = lines(src)
    return '\n'.join(ls[a - 1:(b if b is not None else len(ls))])


HDR = '''/-!
# Frob chain, {n}: {title}

Copyright: this file is part of the fork Deicyde/diophantine-z-q (task frobchain-contrib,
2026-11-13). Generated by `scratch/frobchain-contrib/build_modules.py`.

{body}
-/
'''

TB = 'scratch/unram-tate/TateBridge.lean'
BR = 'scratch/g14-trace/part_bridge.lean'
FR = 'scratch/frob-trace/part_frob.lean'
RG = 'scratch/mul-rigidity/Rigidity.lean'
RED = 'scratch/alg-frob-red/part_red.lean'
FX = 'scratch/afr-absfrob/part_fext.lean'
FP = 'scratch/frob-pieces/part_%s.lean'
G14 = 'scratch/g14-trace/part_g14.lean'
LT97 = 'scratch/linked-tate/parts/97_linkeddata.lean'
LF10 = 'scratch/linked-frob/parts/10_linkedfrob.lean'
LF20 = 'scratch/linked-frob/parts/20_bundle4.lean'

# ---- sanity checks on the sources and the cut points ----
# the copies used by the chain's own assemblies are the owners' files
for a, b in [(TB, 'scratch/frob-trace/part_tate_src.lean'),
             (BR, 'scratch/frob-trace/part_bridge_src.lean'),
             (FR, 'scratch/alg-frob-red/src_part_frob.lean'),
             (RG, 'scratch/alg-frob-red/src_Rigidity.lean'),
             (G14, 'scratch/frob-trace/part_g14_g14.lean')]:
    assert rd(a) == rd(b), (a, b)
tb = lines(TB)
NIMP = 16
assert all(l.startswith('import ') for l in tb[:NIMP]) and not tb[NIMP].startswith('import')
assert tb[51] == ('open CategoryTheory AlgebraicGeometry Limits MonoidalCategory '
                  'CartesianMonoidalCategory MonObj')
assert tb[52] == 'open ZInQ LeafQM.AV GlueDescent GlueDescent.B2 GlueDescent.B2Q GlueDescent.B3Q'
MF_OPENS = tb[51] + '\n' + tb[52] + '\n'   # the file-level opens of g0-mod-field's ModField.lean
rg = lines(RG)
assert all(l.startswith('import ') for l in rg[:4]) and rg[4] == ''
red = lines(RED)
assert red[1362].startswith('/-- **`AbsFrob` (GLUE;') and red[1367] == 'def AbsFrob : Prop :='
assert red[1372] == '        Spec.map (CommRingCat.ofHom (frobenius R p)) ≫ g = g ≫ Fr'
assert red[1373] == ''
# alg-frob-red's `def AbsFrob` (docstring + def) = frob-contrib's adopted copy, character for character
absf = rd('ZInQKernel/Contrib/AbsFrob/AlgFrobRed.lean')
assert '\n'.join(red[1362:1373]) in absf
g14 = lines(G14)
assert g14[25:31] == ['noncomputable section', '', 'namespace G14Trace', '',
                      'open PkgI4 (Qbar GQ LiesOver IsArithFrob GaloisRep)',
                      'open PkgI3 G0ModNewform GlueC10Link'], g14[25:31]
assert g14[145].startswith('/-- **The Frobenius trace link (GLUE, AV side')
assert g14[155].startswith('def FrobTraceLink') and g14[162] == ''
lt = lines(LT97)
assert lt[14] == 'section LinkedDataSec' and lt[23] == 'open G0ModField' and lt[24] == ''
assert lt[124].startswith('/-- **The canonical operators**') and lt[134] == ''
assert lt[127].startswith('def tmOf')
assert lt[192].startswith('/-- **Glue: the Frobenius trace link for the canonical operators**')
assert lt[200] == 'def LinkedFrob : Prop :=' and lt[232] == ''
assert lt[233].startswith('/-- **Glue: Glazer')
lf20 = lines(LF20)
assert lf20[36] == '' and lf20[37].startswith('/-- **`LinkedFrob` from the textbook bundle')
assert lf20[43] == 'end LinkedFrobRed'

modules = []  # (name, imports, title, provenance, text)


def add(name, imports, title, prov, text):
    modules.append((name, imports, title, prov, text))


add('TateBridge', [l[len('import '):] for l in tb[:NIMP]] +
    ['ZInQKernel.HDecomp.C10.Link'],
    'g0-mod-field (`G7Data`, `TateBridge`) and unram-tate (`opV`, `tateBridge_of_tateModuleFree`)',
    'VERBATIM: `scratch/unram-tate/TateBridge.lean` (task unram-tate; its lines 1-1036 are\n'
    '`scratch/g0-mod-field/ModField.lean`, task g0-mod-field) after its 16 import lines, `#print`\n'
    'lines dropped. Imports: its 16 imports and `ZInQKernel.HDecomp.C10.Link` (frob-trace\'s\n'
    'additional import, for `FrobCompare`).',
    noprint(L(TB, NIMP + 1)))

add('Bridge35', [MOD + 'TateBridge'],
    '`G14Bridge.TateBridge35` (g14-trace)',
    'VERBATIM: `scratch/g14-trace/part_bridge.lean` (task g14-trace; frob-trace\'s\n'
    '`part_bridge_src.lean` is the same file), after the context lines: the two file-level `open`\n'
    'lines of g0-mod-field\'s `ModField.lean` (active at this point of frob-trace\'s `FrobTrace.lean`).',
    MF_OPENS + '\n' + noprint(rd(BR)))

add('FrobTrace', [MOD + 'Bridge35'],
    '`AlgFrobRed → AlgFrobOne → AlgFrobLink → TateBridge35` (frob-trace)',
    'VERBATIM: `scratch/frob-trace/part_frob.lean` (task frob-trace), `#print` lines dropped, after\n'
    'the two file-level `open` lines of `ModField.lean`.',
    MF_OPENS + '\n' + noprint(rd(FR)))

add('Rigidity', [l[len('import '):] for l in rg[:4]],
    'rigidity of pointed morphisms of abelian varieties (mul-rigidity)',
    'VERBATIM: `scratch/mul-rigidity/Rigidity.lean` (task mul-rigidity) after its 4 import lines\n'
    '(which are this module\'s imports), `#print` lines dropped.',
    noprint(L(RG, 5)))

add('AlgFrobRed', [MOD + 'FrobTrace', MOD + 'Rigidity', 'ZInQKernel.Contrib.AbsFrob.AlgFrobRed'],
    '`FrobTrace.AlgFrobRed` reduced (alg-frob-red)',
    'VERBATIM: `scratch/alg-frob-red/part_red.lean` (task alg-frob-red), `#print` lines dropped,\n'
    'after the two file-level `open` lines of `ModField.lean`, with ONE deletion: its lines\n'
    '1363-1373, the docstring and `def AlgFrobRedRed.AbsFrob`, which are character-for-character\n'
    'the text adopted by task frob-contrib in `ZInQKernel/Contrib/AbsFrob/AlgFrobRed.lean`\n'
    '(imported here; checked by the generator).',
    MF_OPENS + '\n' + noprint('\n'.join(red[:1362] + red[1373:])))

add('FExtend', [MOD + 'AlgFrobRed'],
    '`FExtendGen` from the Néron mapping property I2-NMP (afr-absfrob)',
    'VERBATIM: `scratch/afr-absfrob/part_fext.lean` (task afr-absfrob), `#print` lines dropped, after\n'
    'the two file-level `open` lines of `ModField.lean`. afr-absfrob\'s other file, `AbsFrobDef.lean`\n'
    '(the absolute Frobenius and `absFrob`), is task frob-contrib\'s `ZInQKernel/Contrib/AbsFrob/`.',
    MF_OPENS + '\n' + noprint(rd(FX)))

add('Pieces', [MOD + 'FExtend', 'ZInQKernel.Contrib.FrobPieces.SmoothGeomConnIntegral'],
    '`GoodRedCofinite` from spreading out; `AlgFrobRed` from N1-g1, Zariski, I2-Red, I2-NMP (frob-pieces)',
    'VERBATIM: `scratch/frob-pieces/part_good.lean`, `part_neron.lean`, `part_final.lean`,\n'
    '`part_full.lean` (task frob-pieces), concatenated with one blank line between them as in\n'
    'scratch/linked-frob/assemble.sh, `#print` lines dropped, after the two file-level `open` lines\n'
    'of `ModField.lean`.',
    MF_OPENS + '\n' + noprint('\n'.join(rd(FP % f) + '\n' for f in ['good', 'neron', 'final', 'full'])))

add('LinkedStatement', [MOD + 'TateBridge'],
    'the statement `UnramTate.LinkedFrob` (linked-tate)',
    'Two VERBATIM slices, no other code:\n'
    '* `scratch/g14-trace/part_g14.lean` (task g14-trace) lines 26-29 (`noncomputable section`,\n'
    '  `namespace G14Trace`) and line 30 (`open PkgI4 (Qbar GQ LiesOver IsArithFrob GaloisRep)`),\n'
    '  then, as context, `open PkgI3 G0ModField.GaloisCopy GlueC10Link` in place of its line 31\n'
    '  `open PkgI3 G0ModNewform GlueC10Link` (g0-mod-newform\'s namespace is not in this build; the\n'
    '  only name of it used, `Vb`, resolves to `G0ModField.GaloisCopy.Vb` of g0-mod-field, whose definition has\n'
    '  the same text as `G0ModNewform.Vb`: `TensorProduct ℚ_[ℓ] (PadicAlgCl ℓ) (A.V ℓ)`), then its\n'
    '  lines 146-162 (docstring and `def FrobTraceLink`), then `end G14Trace` / `end`;\n'
    '* `scratch/linked-tate/parts/97_linkeddata.lean` (task linked-tate) lines 15-25 (section,\n'
    '  `noncomputable section`, its `open`s, `namespace UnramTate`), lines 125-135 (docstring and\n'
    '  `def tmOf`), lines 193-233 (docstring and `def LinkedFrob`), then `end UnramTate` / `end` /\n'
    '  `end LinkedDataSec` (its lines 445, 475, 477).\n'
    'linked-tate compiled these texts over `scratch/h-decomposition/Leaves.lean`, whose definitions\n'
    'are copies of the kernel\'s; here they are compiled over the kernel (`ZInQKernel.HDecomp.*`) and\n'
    'g0-mod-field/unram-tate (`TateBridge.lean`), as frob-trace\'s files are.',
    L(G14, 26, 30) + '\nopen PkgI3 G0ModField.GaloisCopy GlueC10Link\n\n' + L(G14, 146, 162) +
    '\n\nend G14Trace\n\nend\n\n' + L(LT97, 15, 25) + '\n' + L(LT97, 125, 135) + '\n' +
    L(LT97, 193, 233) + '\nend UnramTate\n\nend\n\nend LinkedDataSec\n')

add('LinkedFrob', [MOD + 'LinkedStatement', MOD + 'Pieces'],
    '`UnramTate.LinkedFrob` from the frob chain (linked-frob)',
    'VERBATIM: after the two file-level `open` lines of `ModField.lean` (active at this point of\n'
    'linked-frob\'s `LinkedFrob.lean`, where they make `GQ` mean `GlueDescent.B2Q.GQ`),\n'
    '`scratch/linked-frob/parts/10_linkedfrob.lean` (task linked-frob), then lines 1-37\n'
    'of `scratch/linked-frob/parts/20_bundle4.lean` (`linkedFrob_of_gen`,\n'
    '`linkedFrob_of_goodRed_nmp`, `linkedFrob_of_neron_nmp`), then `end LinkedFrobRed` / `end` /\n'
    '`end LinkedFrobBundleSec`. Not copied: `linkedFrob_of_textbook` and `HSyn.GluePieces4` (they\n'
    'take Leaves.lean\'s bundles `HSyn.TextbookLeaves`, `HSyn.ResearchLeaves`, which are not in the\n'
    'kernel build).',
    MF_OPENS + '\n' + noprint(rd(LF10)) + '\n' + L(LF20, 1, 37) + '\nend LinkedFrobRed\n\nend\n\nend LinkedFrobBundleSec\n')

for n, (name, imports, title, prov, text) in enumerate(modules, 1):
    out = ''.join('import %s\n' % i for i in imports) + '\n'
    out += HDR.format(n=n, title=title, body=prov) + '\n' + text.rstrip('\n') + '\n'
    with open(D + name + '.lean', 'w') as f:
        f.write(out)
    print(D + name + '.lean', out.count('\n'), 'lines')
