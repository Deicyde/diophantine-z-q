# Generates the integer certificate section of Global.lean from cert.py's data.
import runpy, io, contextlib
buf = io.StringIO()
with contextlib.redirect_stdout(buf):
    g = runpy.run_path('scratch/glue-vigneras/cert.py')
entries, mons, solve = g['entries'], g['mons'], g['solve']
from math import lcm
def poly_lean(p):
    terms = []
    for m, c in sorted(p.items()):
        mon = '*'.join(f'n {i}' if e == 1 else f'n {i}^2' for i, e in enumerate(m) if e)
        terms.append(f'({int(c)})*{mon}')
    return ' + '.join(terms) if terms else '0'
out = []
out.append('/-- `Eint n k l`: coordinate `l` (N5\'s basis) of `x eₖ x̄` for `x = comb n` (generated by `gen_global.py`). -/')
out.append('def Eint (n : Fin 4 → ℤ) : Fin 4 → Fin 4 → ℤ := ![')
rows = []
for k in range(4):
    rows.append('  ![' + ', '.join(poly_lean(entries[4*k+l][1]) for l in range(4)) + ']')
out.append(',\n'.join(rows) + ']')
names = []
for idx, m in enumerate(mons):
    a, b = [i for i, e in enumerate(m) for _ in range(e)]
    sol, rk = solve([1 if mm == m else 0 for mm in mons])
    D = lcm(*[s.denominator for s in sol]); f = 6 // D
    rhs = ' + '.join(f'({int(s*D*f)}) * Eint n {r//4} {r%4}' for r, s in enumerate(sol) if s != 0)
    nm = f'cert_{a}{b}'; names.append((a, b, nm))
    out.append(f'theorem {nm} (n : Fin 4 → ℤ) : 6 * (n {a} * n {b}) = {rhs} := by\n  simp [Eint]; ring')
print('\n\n'.join(out))
print('-- names:', names)
