#!/usr/bin/env python3
"""Assemble RayClassCFT.lean (one file, no scratch imports) from the olean-chain parts."""
import re, sys
parts = ["Base.lean", "RayDefs.lean", "RayProof1.lean", "RayProof2.lean", "RayProof3.lean",
         "RayProof4.lean", "RayProof5.lean", "RayGlueO.lean", "RayGlueI.lean", "RayGlueA.lean"]
extra = sys.argv[1:]
parts += extra
local = {p[:-5] for p in parts}
imports, bodies = [], []
for p in parts:
    lines = open(p).read().split("\n")
    body = []
    for l in lines:
        m = re.match(r"^import (\S+)", l)
        if m:
            if m.group(1) not in local and l not in imports:
                imports.append(l)
        else:
            body.append(l)
    bodies.append(f"\n/-! ===== part: scratch/rayclass-cft/{p} ===== -/\n" + "\n".join(body))
hdr = "\n".join(imports) + "\n\n/-! # rayclass-cft: `ShimuraGlue.Ray.RayClassCM` from published-form leaves\n\nGenerated by `mk.py` from the parts listed below (each part compiles on its own over an olean chain;\nthis file is the one-file check). Report: `docs/research/rayclass-cft.md`. -/\n"
open("RayClassCFT.lean", "w").write(hdr + "\n".join(bodies))
print("wrote RayClassCFT.lean with", len(parts), "parts")
