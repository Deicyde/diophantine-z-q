"""g8-local: check that the target Props in the assembled scratch/g8-local/G8Local.lean are
verbatim copies of their owners' texts (g8-object's part files), and that the derived texts of
part_link2.lean are what py/gen_link2.py produces.
Run from the worktree root: python3 scratch/g8-local/py/verbatim_check.py"""
import re, subprocess
asm = open('scratch/g8-local/G8Local.lean').read()
owners = {
    'scratch/g8-object/part_split.lean': ['ContainsL', 'WildTateTrivial', 'LocalDataS',
                                          'LinkedTateObjS', 'LinkedTateObjD', 'LinkedTateDataD',
                                          'OnL'],
    'scratch/g8-object/part_link.lean': ['BetaUpperC', 'BetaTameC', 'LocalDataC', 'LinkedTateObj'],
    'scratch/g8-object/part_obj.lean': ['TmWild', 'BetaUpper', 'BetaTame', 'LocalDataG'],
}
ok = True
for f, names in owners.items():
    src = open(f).read()
    for n in names:
        m = re.search(r"(/--(?:(?!-/).)*?-/\n)?def " + n + r"\b.*?(?=\n\n)", src, re.S)
        found = m is not None and m.group(0) in asm
        ok &= found
        print(f"{n:18s} ({f.split('/')[-1]}): verbatim in G8Local.lean: {found}")
gen = subprocess.run(['python3', 'scratch/g8-local/py/gen_link2.py'], capture_output=True,
                     text=True).stdout
lp, core = gen.split("def LinkedTateObjSCore")
core = "def LinkedTateObjSCore" + core
for name, txt in [('LocalPartS', lp), ('LinkedTateObjSCore', core)]:
    found = txt.strip() in asm
    ok &= found
    print(f"{name:18s} (generated by gen_link2.py): in G8Local.lean: {found}")
print("ALL OK" if ok else "MISMATCH")
