"""Generate scratch/pb-p1/BypassFold.lean: the fold of panPrintedP + bergerPrintedV -> panPrintedF + bergerSurveyF.

Pan's and Berger's leaves restated over Fontaine's B_st (pb-p1) give r11r12 : PanBerger directly
(PanDict.panBerger_of_F), but the new Pan leaf does not give the old field panPrintedP (that would need the
comparison B_max[log p~]-pst => B_cris[log p~]-pst). So the fold copies the research generations 40..45 (the ones
carrying panPrintedP and bergerPrintedV, TailZ65..TailZ71) into the namespace HDec.HSyn.PBP1 with the two fields
replaced, copies their conversion maps, and edits the one consumer (TailZ65's r11r12 line). Name resolution
inside the namespace picks the copies; OpenResearchLeaves39 and sixContactMin_of_open57_k954 are the originals.
Run from the repository root:  python3 scratch/pb-p1/gen_bypass.py > scratch/pb-p1/BypassFold.lean
"""
import re, sys

H = 'ZInQKernel/OneProof/H/'
NL = '\n'
GENFILE = {40: 65, 41: 66, 42: 67, 43: 68, 44: 70, 45: 71}

PAN_OLD = '  panPrintedP : _root_.HDec.PkgI4.PanDict.PanPrintedP'
BER_OLD = '  bergerPrintedV : _root_.HDec.PkgI4.PanDict.BergerPrintedV'
PAN_DOC = ('  /-- R12 (pb-p1). Pan, J. Amer. Math. Soc. 35 (2022), Theorem 1.0.4 (= arXiv:1901.07166v2 Thm 1.0.4 p. 5 with '
           'Conj. 1.0.1 p. 2), p >= 5, printed form with "potentially semi-stable in the sense of Fontaine" over '
           "Fontaine's B_st = B_cris[log p~] inside B_dR (Berger, arXiv:math/0210184v1, II.3.1 and II.3.3), basis form, "
           'on a model V = E^n; otherwise as pb-fix3\'s PanPrintedP. -/')
BER_DOC = ("  /-- R11 (pb-p1). Berger's theorem (Invent. Math. 148 (2002) Thm 0.7) in the printed form of Berger, An "
           'introduction to the theory of p-adic representations (arXiv:math/0210184v1, IV.5.1 p. 30, IV.5.3 p. 31): '
           "a de Rham p-adic representation V = E^n of G_Qp is potentially semistable over Fontaine's "
           'B_st = B_cris[log p~] (II.3.1, II.3.3), basis form (I.2.3). -/')
PAN_NEW = '  panPrintedF : _root_.HDec.PkgI4.PanDict.PanPrintedF'
BER_NEW = '  bergerSurveyF : _root_.HDec.PkgI4.PanDict.BergerSurveyF'


def lines(fn):
    return open(fn).read().split(NL)


def struct_block(fn, name):
    L = lines(fn)
    for i, l in enumerate(L):
        if l.startswith(f'structure {name} : Prop where'):
            j = i + 1
            while j < len(L) and L[j].strip() != '' and not L[j].startswith(('theorem', 'def', 'structure', 'end')):
                j += 1
            return L[i:j]
    sys.exit(f'structure {name} not found in {fn}')


def map_block(fn, name):
    L = lines(fn)
    for i, l in enumerate(L):
        if l.startswith(f'theorem {name} '):
            j = i + 1
            while j < len(L) and L[j].strip() != '':
                j += 1
            return L[i:j]
    sys.exit(f'theorem {name} not found in {fn}')


def swap_field(B, old, doc, new, what):
    hits = [i for i, l in enumerate(B) if l.rstrip() == old]
    if len(hits) != 1:
        sys.exit(f'{what}: {len(hits)} hits for {old!r}')
    i = hits[0]
    k = i
    if B[i - 1].rstrip().endswith('-/'):
        k = i - 1
        while not B[k].lstrip().startswith('/--'):
            k -= 1
    return B[:k] + [doc, new] + B[i + 1:]


def swap_assign(B, what):
    out, n = [], 0
    for l in B:
        if l.rstrip() == '  panPrintedP := n.panPrintedP':
            out.append('  panPrintedF := n.panPrintedF'); n += 1
        elif l.rstrip() == '  bergerPrintedV := n.bergerPrintedV':
            out.append('  bergerSurveyF := n.bergerSurveyF'); n += 1
        elif l.startswith('  r11r12 := _root_.HDec.PkgI4.PanDict.panBerger_of_printedPV n.panPrintedP n.bergerPrintedV '):
            out.append(l.replace('panBerger_of_printedPV n.panPrintedP n.bergerPrintedV',
                                 'panBerger_of_F n.panPrintedF n.bergerSurveyF')); n += 10
        else:
            if 'panPrintedP' in l or 'bergerPrintedV' in l:
                sys.exit(f'{what}: unexpected use: {l}')
            out.append(l)
    return out, n


out = []
P = out.append
P('import ZInQKernel.OneProof.H.TailZ71')
P('import ZInQKernel.Contrib.OneProof.PanBergerFontaine')
P('')
P('/-! # pb-p1: fold of `panPrintedP` + `bergerPrintedV` into `panPrintedF` + `bergerSurveyF` (generated by')
P('scratch/pb-p1/gen_bypass.py; scratch check, not a tree module)')
P('')
P("Both new leaves use Fontaine's `B_st = B_cris[log [p̃]]` (Pan's own sense; Berger's survey prints Berger's theorem")
P('over it), and `PanDict.panBerger_of_F` proves `r11r12 : PanBerger` from them with no comparison of period rings.')
P("The new Pan leaf does not give the old field `panPrintedP` (that would need `B_max[log [p̃]]`-pst => Fontaine-pst),")
P('so the conversion bypasses the generations 40..45: the namespace `PBP1` copies them with the two fields replaced,')
P('copies their conversion maps, and edits the one consumer (TailZ65, `r11r12`).')
P('-/')
P('')
P('namespace HDec')
P('')
P('namespace HSyn')
P('')
P('namespace PBP1')
P('')
total = 0
for k in range(40, 46):
    fn = f'{H}TailZ{GENFILE[k]}.lean'
    S = struct_block(fn, f'OpenResearchLeaves{k}')
    S = swap_field(S, PAN_OLD, PAN_DOC, PAN_NEW, f'gen {k} pan')
    S = swap_field(S, BER_OLD, BER_DOC, BER_NEW, f'gen {k} berger')
    P(f'/-- pb-p1 copy of `HDec.HSyn.OpenResearchLeaves{k}` with `panPrintedP`, `bergerPrintedV` replaced by '
      '`panPrintedF`, `bergerSurveyF`. -/')
    out.extend(S)
    P('')
    M = map_block(fn, f'openResearchLeaves{k - 1}_of_OpenResearchLeaves{k}')
    M, n = swap_assign(M, f'map {k}')
    total += n
    P(f'/-- pb-p1 copy of `HDec.HSyn.openResearchLeaves{k - 1}_of_OpenResearchLeaves{k}`'
      + (" (target: the original generation 39; `r11r12` by `PanDict.panBerger_of_F`)." if k == 40 else '.') + ' -/')
    out.extend(M)
    P('')
if total != 10 + 2 * 5:
    sys.exit(f'unexpected number of edits: {total}')
P('/-- **G0 with only the open leaves and the open glue**, Pan and Berger over Fontaine\'s `B_st` (pb-p1 bypass of')
P('generations 40..45; `sixContactMin_of_open57_k954` is the original). -/')
P('theorem sixContactMin_of_open65 (r : OpenResearchLeaves45) (t : OpenTextbookLeaves17) (l : OpenAddedLeaves26) :')
P('    ZInQ.SixContactMin :=')
P('  sixContactMin_of_open57_k954 (openResearchLeaves39_of_OpenResearchLeaves40 (openResearchLeaves40_of_OpenResearchLeaves41')
P('    (openResearchLeaves41_of_OpenResearchLeaves42 (openResearchLeaves42_of_OpenResearchLeaves43')
P('      (openResearchLeaves43_of_OpenResearchLeaves44 (openResearchLeaves44_of_OpenResearchLeaves45 r)))))) t l')
P('')
P('end PBP1')
P('')
P('end HSyn')
P('')
P('end HDec')
P('')
P('#print axioms HDec.HSyn.PBP1.sixContactMin_of_open65')
print(NL.join(out))
