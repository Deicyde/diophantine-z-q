"""cm-fold-rebase: generate ZInQKernel/Contrib/OneProof/CMFoldRebase/Top3.lean.

The bost-gr9 reroute (main's TailZ80) copied the chain sixContactMin_of_open72 -> ... -> open8 into HDec.HSyn.GR9.
This walks that copied chain from GR9.sixContactMin_of_open48_eb_k954 down to the first callee that is not in GR9
(sixContactMin_of_open7_hf_pz_eb, unchanged by bost-gr9), and copies each one-step theorem verbatim, in its own
namespace and context, with (c : CMBranch.CMInputs2) threaded and the callee renamed `<callee>_cm2 (c := c)`
(cm-branch2's mk_top2.py, made namespace-aware). The last callee, HSyn.sixContactMin_of_open7_hf_pz_eb_cm2, is
cm-branch2's (CMBranch/Top2.lean): the base switched to the manuscript's CM branch.
"""
import re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
import leanctx
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../..'))
F = os.path.join(ROOT, 'ZInQKernel/OneProof/H/TailZ80.lean')
L = leanctx.lines_of(F)
GR9_START = 84  # 0-based: the GR9 copies start after the new generation (line 85)

def find(name):
    hits = [i for i, l in enumerate(L) if i >= GR9_START and re.match(r'^theorem ' + re.escape(name) + r'(?=[\s(])', l)]
    if not hits: return None
    assert len(hits) == 1, name
    a = hits[0]; b = a + 1
    while b < len(L) and L[b].startswith(' '): b += 1
    # docstring directly above
    s = a
    if L[s - 1].rstrip().endswith('-/'):
        while not L[s - 1].startswith('/--'): s -= 1
        s -= 1
    return s, a, b

chain = []
cur = 'sixContactMin_of_open48_eb_k954'
while True:
    r = find(cur)
    if r is None: break
    s, a, b = r
    t = '\n'.join(L[a:b]).rstrip()
    body = t.split(':=', 1)[1]
    calls = [c for c in re.findall(r"(sixContactMin_of_[A-Za-z0-9_']+)", body) if c != cur]
    chain.append((cur, s, a, b, calls[0])); cur = calls[0]
print('bottom callee (outside GR9):', cur)
out = []
for name, s, a, b, callee in reversed(chain):
    t = '\n'.join(L[a:b]).rstrip()
    i = t.index('ZInQ.SixContactMin :=')
    j = t.rindex(':', 0, i)
    sig = t[:j].rstrip() + ' (c : CMBranch.CMInputs2) ' + t[j:i] + 'ZInQ.SixContactMin :='
    sig = sig.replace('theorem ' + name, 'theorem ' + name + '_cm2', 1)
    body = t[i + len('ZInQ.SixContactMin :='):]
    assert len(re.findall(re.escape(callee) + r'(?![\w\'])', body)) == 1, (name, callee)
    body = re.sub(re.escape(callee) + r'(?![\w\'])', callee + '_cm2 (c := c)', body)
    ns, ctx = leanctx.context(F, a + 1)
    assert ns == 'HDec.HSyn.GR9', (name, ns)
    blk = [f'-- copied from ZInQKernel/OneProof/H/TailZ80.lean:{a + 1} (HDec.HSyn.GR9.{name}), c threaded',
           'section', 'namespace HDec.HSyn.GR9'] + ctx + [
           f'/-- `GR9.{name}` (bost-gr9) with the base switched to `sixContactMin_of_open4_hf_pz_eb_cm2` (cm-branch2, '
           'the manuscript\'s CM branch); generated by `scratch/cm-fold-rebase/gen/mk_top3.py`. -/',
           sig + body, 'end HDec.HSyn.GR9', 'end', '']
    out.append('\n'.join(blk))
hdr = '''import ZInQKernel.OneProof.H.TailZ83
import ZInQKernel.Contrib.OneProof.CMBranch.R5Prune

/-! # cm-fold-rebase: the CM-branch chain on main's bost-gr9 reroute (generated by `scratch/cm-fold-rebase/gen/mk_top3.py`)

Main's `sixContactMin_of_open73` (TailZ80, bost-gr9) runs through the copied chain `HDec.HSyn.GR9`. Each theorem
`GR9.sixContactMin_of_openN…` from `open48_eb_k954` down to `open8_hf_pz_eb` is copied verbatim with the CM-branch
inputs `c : CMBranch.CMInputs2` threaded and its callee renamed `…_cm2 (c := c)`; the last callee is cm-branch2's
`HSyn.sixContactMin_of_open7_hf_pz_eb_cm2` (`CMBranch/Top2.lean`), whose base is the manuscript's CM branch. -/

set_option maxHeartbeats 1000000
set_option linter.style.longLine false
noncomputable section

'''
os.makedirs(os.path.join(ROOT, 'ZInQKernel/Contrib/OneProof/CMFoldRebase'), exist_ok=True)
open(os.path.join(ROOT, 'ZInQKernel/Contrib/OneProof/CMFoldRebase/Top3.lean'), 'w').write(hdr + '\n'.join(out) + '\nend\n')
print(len(chain), [c[0] for c in chain])
