"""Generate WithProductHeight.lean: product-height's ProductHeight.lean (verbatim, minus its
#print lines) + §1-§4 of ProductUnif.lean (without the §0 copy) + the composite theorem.
Run from the worktree root: ~/pyenv/bin/python scratch/product-unif/build_with_product_height.py"""
ph = open('scratch/product-height/ProductHeight.lean').read()
pu = open('scratch/product-unif/ProductUnif.lean').read()
ph_body = '\n'.join(l for l in ph.splitlines() if not l.startswith('#print'))
ph_body = ph_body.replace('import ZInQKernel.HDecomp.Faltings.H5Neron\n', '')
imports = '\n'.join(l for l in pu.splitlines() if l.startswith('import '))
start = pu.index('/-! ## §1. Elementary analysis')
end = pu.index('#print axioms')
tail = '''
namespace ZInQ.ProductUnif

/-- **P2 from the S-alg reduction (proved).** `ProductModelHeight` (the type of
`GluePieces.productModelHeight`) from `HodgeLatticeTheorem` and the three new glue Props;
`ProductUnifSplits` is now a theorem. -/
theorem productModelHeight_of_salg (hH : DefFaltings.HodgeLatticeTheorem)
    (hD : ProductUnifDims) (hJ : JacDetDescends) (hP : ProductHodgeAdd) :
    ZInQ.H5Neron.ProductModelHeight :=
  ZInQ.ProductHeight.productModelHeight_of_splits productUnifSplits
    (productMetrizationOfProductUnif_of hH hD hJ hP)

/-- **P2 from the finest reduction (proved).** -/
theorem productModelHeight_of_salg' (hH : DefFaltings.HodgeLatticeTheorem)
    (hD : ProductUnifDims) (hJ : JacDetDescends) (hS : ProductHodgeSections) :
    ZInQ.H5Neron.ProductModelHeight :=
  productModelHeight_of_salg hH hD hJ (productHodgeAdd_of hS)

end ZInQ.ProductUnif

#print axioms ZInQ.ProductUnif.productUnifSplits
#print axioms ZInQ.ProductUnif.productModelHeight_of_salg'
#print axioms ZInQ.ProductUnif.productMetrizationOfProductUnif_of
#print axioms ZInQ.ProductUnif.productModelHeight_of_salg
'''
out = (imports.replace('import ZInQKernel.HDecomp.Faltings.Height',
                       'import ZInQKernel.HDecomp.Faltings.H5Neron') + '\n\n'
       + '/-! Generated by build_with_product_height.py: `scratch/product-height/ProductHeight.lean`\n'
       + '(verbatim) followed by §1-§4 of `ProductUnif.lean`. -/\n\n'
       + ph_body + '\n\n' + pu[start:end] + tail)
open('scratch/product-unif/WithProductHeight.lean', 'w').write(out)
