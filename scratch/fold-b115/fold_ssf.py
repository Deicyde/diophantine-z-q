#!/usr/bin/env python3
"""fold-b115 fold 1: ss-faltings (bypass; sga7_IX_Cor3_3_Def34 -> faltingsSemistableHeightBC), reproducible.

Run from the repository root of a head that has ss-faltings' Contrib files (SSFaltings, SSFaltingsGR9, SSFChain) and
whose Main top is the one SSFChain was generated on (`sixContactMin_of_open76`, TailZ83). If the top moved, first
regenerate SSFChain (scratch/ss-faltings/TaintS.lean two lines, then gen/gen_chain.py; see docs/research/ss-faltings.md
section 3) and pass the generator arguments below.

    python3 scratch/fold-b115/fold_ssf.py [TOP_MODULE R0 OLD_TOP NEWR NEW_TOP TEXTBOOK ADDED]

It runs ss-faltings' gen_bypass.py (same arguments; writes scratch/ss-faltings/BypassFold.lean and kinds-rows.tsv),
moves the module to ZInQKernel/OneProof/H/TailZ<j>.lean (j = next free number; the final `#print axioms` dropped),
moves the generated chain Contrib/OneProof/SSFChain.lean to OneProof/H/SSFChain.lean (with the earlier copy reroutes),
switches Main's import, frozenTarget's research bundle and top theorem, adds a docstring paragraph to Main, and
replaces the kinds.tsv row of sga7_IX_Cor3_3_Def34 by the generated row (claims.tsv has no row for it).
"""
import os, re, subprocess, sys

ARGS = sys.argv[1:]
D = ['ZInQKernel.OneProof.H.TailZ83', 'OpenResearchLeaves57', 'sixContactMin_of_open76', 'OpenResearchLeaves58',
     'sixContactMin_of_open77', 'OpenTextbookLeaves18', 'OpenAddedLeaves27']
TOPMOD, R0, OLD_TOP, NEWR, NEW_TOP, TB, AD = ARGS + D[len(ARGS):]


def die(m):
    sys.exit('fold_ssf: ' + m)


subprocess.run([sys.executable, 'scratch/ss-faltings/gen/gen_bypass.py', TOPMOD, R0, OLD_TOP, NEWR, NEW_TOP, TB, AD], check=True)
src = 'scratch/ss-faltings/BypassFold.lean'
text = open(src).read()
text = re.sub(r'\n#print axioms [^\n]*\n*$', '\n', text)
hdir = 'ZInQKernel/OneProof/H'
nums = [int(m.group(1)) for f in os.listdir(hdir) if (m := re.fullmatch(r'TailZ(\d+)\.lean', f))]
j = max(nums) + 1
newmod = f'ZInQKernel.OneProof.H.TailZ{j}'
# The generated chain copy goes under OneProof/H like the earlier copy reroutes (NoSGA3Copy, GoodModelIsoCopy,
# EichlerBoundCopy): in Contrib/OneProof, #discharges (DischargesTest, CONTRIBUTING.md's worked example) lists every
# projection of its copied bundles as a self-match (231 lines).
chain_c, chain_h = 'ZInQKernel/Contrib/OneProof/SSFChain.lean', f'{hdir}/SSFChain.lean'
if os.path.exists(chain_c):
    subprocess.run(['git', 'mv', chain_c, chain_h], check=True)
if not os.path.exists(chain_h):
    die('SSFChain.lean not found')
text = text.replace('import ZInQKernel.Contrib.OneProof.SSFChain\n', 'import ZInQKernel.OneProof.H.SSFChain\n')
text = text.replace('`Contrib/OneProof/SSFChain.lean`', '`OneProof/H/SSFChain.lean`')
open(f'{hdir}/TailZ{j}.lean', 'w').write(text)
os.remove(src)  # the module now lives under ZInQKernel/OneProof/H (the .lean.txt copy in scratch stays)

mp = 'ZInQKernel/OneProof/Main.lean'
m = open(mp).read()
old_import = f'import {TOPMOD}\n'
if old_import not in m:
    die(f'Main does not import {TOPMOD}')
m = m.replace(old_import, f'import {newmod}\n', 1)
for a, b in [(f'(r : HDec.HSyn.{R0})', f'(r : HDec.HSyn.{NEWR})'),
             (f'(HDec.HSyn.{OLD_TOP} r t l)', f'(HDec.HSyn.{NEW_TOP} r t l)')]:
    if a not in m:
        die(f'Main lacks {a}')
    m = m.replace(a, b, 1)
para = (
    f'ss-faltings (folded by fold-b115) replaced the research field `sga7_IX_Cor3_3_Def34` (SGA 7 IX Cor. 3.3, not in the\n'
    f'manuscript\'s bibliography) by `faltingsSemistableHeightBC` (Faltings 1983 section 1, invariance of the height of a\n'
    f'semistable abelian variety under finite extension; the manuscript uses it uncited at L596-598); the field of\n'
    f'semistable reduction is proved from Raynaud\'s criterion over `K(A[15])` (`Contrib/OneProof/SSFaltings.lean`).\n'
    f'`{NEWR}` (`TailZ{j}`) is `{R0}` with the field replaced, and `HDec.HSyn.{NEW_TOP}` goes through\n'
    f'`{OLD_TOP}_sf`, a copy of the chain of declarations that carry the field (`OneProof/H/SSFChain.lean`,\n'
    f'generated by `scratch/ss-faltings/gen/gen_chain.py`; bypass); no existing declaration is changed.\n\n')
anchor = 'The hypotheses of `frozenTarget` are therefore exactly the open statements.'
if anchor not in m:
    die('Main docstring anchor missing')
m = m.replace(anchor, para + anchor, 1)
open(mp, 'w').write(m)

kp = 'docs/one-proof/kinds.tsv'
rows = open(kp).read().split('\n')
new = open('scratch/ss-faltings/kinds-rows.tsv').read().rstrip('\n').split('\n')[1]
hits = [i for i, r in enumerate(rows) if r.split('\t')[1:2] == ['sga7_IX_Cor3_3_Def34']]
if len(hits) != 1:
    die('kinds.tsv: expected one sga7_IX_Cor3_3_Def34 row')
rows[hits[0]] = new
open(kp, 'w').write('\n'.join(rows))
print(f'wrote {hdir}/TailZ{j}.lean; Main -> {NEW_TOP} on {NEWR}; kinds row replaced')
