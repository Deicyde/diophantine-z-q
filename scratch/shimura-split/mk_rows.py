# Builds Rows.lean = coarse-factor's Discharge.lean (verbatim body) + Bridge.lean + Y3Conn.lean + Count.lean
# (bodies verbatim, imports merged) + parts/RowsNew.lean
D=open('scratch/coarse-factor/Discharge.lean').read().split('\n')
srcs=[open('scratch/shimura-split/%s.lean'%n).read().split('\n') for n in ['Bridge','Y3Conn','Count']]
N=open('scratch/shimura-split/parts/RowsNew.lean').read()
imps=[l for l in D if l.startswith('import ')]
for S in srcs:
    for l in S:
        if l.startswith('import ') and l not in imps and 'HDecomp.QM.Leaves' not in l:
            imps.append(l)
body=lambda L: '\n'.join(l for l in L if not l.startswith('import '))
hdr='''/-! shimura-split Rows.lean: generated by scratch/shimura-split/mk_rows.py.
Part 1: scratch/coarse-factor/Discharge.lean (verbatim, imports merged).
Parts 2-4: scratch/shimura-split/Bridge.lean, Y3Conn.lean, Count.lean (verbatim, imports merged).
Part 5: scratch/shimura-split/parts/RowsNew.lean. -/
'''
out='\n'.join(imps)+'\n'+hdr+body(D)+'\n'+'\n'.join(body(S) for S in srcs)+'\n'+N
open('scratch/shimura-split/Rows.lean','w').write(out)
