# Builds H1.lean = coarse-factor's Discharge.lean (verbatim body) + Bridge.lean (body) + parts/H1New.lean
import re
D=open('scratch/coarse-factor/Discharge.lean').read().split('\n')
B=open('scratch/shimura-split/Bridge.lean').read().split('\n')
N=open('scratch/shimura-split/parts/H1New.lean').read()
dimp=[l for l in D if l.startswith('import ')]
bimp=[l for l in B if l.startswith('import ')]
imps=dimp+[l for l in bimp if l not in dimp and 'HDecomp.QM.Leaves' not in l]
dbody='\n'.join(l for l in D if not l.startswith('import '))
bbody='\n'.join(l for l in B if not l.startswith('import '))
hdr='''/-! shimura-split H1.lean: generated by scratch/shimura-split/mk_h1.py.
Part 1: scratch/coarse-factor/Discharge.lean (verbatim, imports merged).
Part 2: scratch/shimura-split/Bridge.lean (verbatim, imports merged).
Part 3: scratch/shimura-split/parts/H1New.lean. -/
'''
open('scratch/shimura-split/H1.lean','w').write('\n'.join(imps)+'\n'+hdr+dbody+'\n'+bbody+'\n'+N)
