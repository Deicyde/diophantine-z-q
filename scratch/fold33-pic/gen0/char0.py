def ren(txt):
    for a, b in REN.items():
        txt = re.sub(r"(?<![\w'])((?:PhiSurj\.|PicDict\.|T09Pic\.)?)" + re.escape(a) + r"(?![\w'])",
                     lambda m: b if m.group(1) in ("PicDict.", "T09Pic.") and b[0].isupper() else m.group(1) + b, txt)
    return txt

def sub1(txt, a, b, cnt=1):
    n = txt.count(a)
    assert n == cnt, (a, n, txt[:200])
    return txt.replace(a, b)

H2 = "PicZeroChar0.PicZeroAbVar0"
def h2(txt):
    txt = re.sub(r"\(h2 : (T09Pic\.)?PicZeroAbVar\)", "(h2 : " + H2 + ")", txt)
    assert "PicZeroAbVar)" not in txt
    return txt

