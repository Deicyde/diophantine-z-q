import re, sys

C = "ZInQKernel/Contrib/OneProof/"

def decl(path, name):
    s = open(path).read()
    m = re.search(r"^((?:/--(?:[^-]|-(?!/))*-/\n)?)(theorem|lemma|def) " + re.escape(name) + r"\b", s, re.M)
    assert m, (path, name)
    start = m.start()
    rest = s[m.end():]
    e = re.search(r"^(/--|theorem |lemma |def |end |namespace |section |open |variable |noncomputable |@\[|instance )", rest, re.M)
    body = rest[: e.start()] if e else rest
    return (s[start:m.end()] + body).rstrip() + "\n"

