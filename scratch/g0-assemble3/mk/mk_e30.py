"""Generate parts/e25_hodgeclosed.lean (infra-smooth-dim's closed_part) and parts/e30_unifdims.lean (unif-dims' Leaves-world
integration, after scratch/unif-dims/build_leaves.py) (repo root, python3 -I)."""
cp=open('scratch/infra-smooth-dim/closed_part.lean.part').read()
cp='\n'.join(l for l in cp.split('\n') if not l.startswith('#print'))
a=cp.index('namespace InfraSmoothDim'); b=cp.index('end InfraSmoothDim')
cp=cp[:a]+cp[a:b].replace('PkgI3.AbVar','ZInQ.DefFaltings.AbVar')+cp[b:]
