#!/usr/bin/env python3
"""Generate the local Tate-duality bypass from the base declarations.

Like the fold-c8 and d2a6b generators, copy the carrier and only the affected
forwarders/readers. Existing research/textbook bundles and unrelated terms
are reused. This script writes two new Lean files and a proposed kinds row.
"""
import csv
from pathlib import Path
import re
import sys

sys.path.insert(0, "scripts/one_proof")
import autofold
import render_open

SCRATCH = Path(__file__).parent
CONTRIB = Path("ZInQKernel/Contrib/OneProof")
H = Path(autofold.H)
MAIN = Path(autofold.MAIN)
CHAIN = CONTRIB / "T10NarrowChain.lean"
DRY = SCRATCH / "DryRun.lean"

src_main, bundles, top, _, last, _ = autofold.main_state()
assert (top, last) == ("sixContactMin_of_open86", "TailZ93")
assert [n for _, n in bundles] == [
    "OpenResearchLeaves67", "OpenTextbookLeaves18", "OpenAddedLeaves28"
]

locs = [
    (H / "TailZ87.lean", "OpenAddedLeaves28"),
    (H / "TailZ87.lean", "c8Leaves_of_OpenAddedLeaves28"),
    (CONTRIB / "NOSNarrowChain.lean", "openResearchLeaves60_y3x6_of_OpenResearchLeaves63_nos"),
    (CONTRIB / "NOSNarrowChain.lean", "sixContactMin_of_open82_nos"),
    (CONTRIB / "NOSNarrowChain.lean", "sixContactMin_of_open83_nos"),
    (H / "TailZ91.lean", "sixContactMin_of_open84"),
    (H / "TailZ92.lean", "openResearchLeaves65_of_OpenResearchLeaves66"),
    (H / "TailZ92.lean", "sixContactMin_of_open85"),
    (H / "TailZ93.lean", top),
]
replacements = {n: n + "_t10" for _, n in locs}
replacements["OpenAddedLeaves28"] = "OpenAddedLeaves29_t10"
replacements["c8Leaves_of_OpenAddedLeaves28"] = "c8Leaves_of_OpenAddedLeaves29_t10"
for n in ("deRhamVpAbVarDirect_of_scholzeH1Milne", "hodgeTateDecompOr_of_scholzeH1Milne",
          "hodgeTateDecompAbVar_of_scholzeH1"):
    replacements[n] = n + "_loc"
replacements.update(t10TateDuality="t10TateDualityLocal",
                    T10_TateDuality="T10_TateDualityLocal",
                    frozenTarget="frozenTarget_t10")
pattern = re.compile(r"\b(?:" + "|".join(replacements) + r")\b")


def replace(src):
    return pattern.sub(lambda m: replacements[m[0]], src)


def extract(path, name, kind="theorem"):
    src = path.read_text()
    # Source declarations have one header followed only by indented lines.
    hit, = re.finditer(rf"^{kind} {re.escape(name)}(?!\w)[^\n]*(?:\n +[^\n]*)*",
                       src, re.M)
    line = src.count("\n", 0, hit.start()) + 1
    return line, hit[0]


def field_only(decl):
    return "\n".join(s for i, s in enumerate(decl.splitlines())
                     if i == 0 or re.match(r"^  \w+ :", s))


text = [
    f"import ZInQKernel.OneProof.H.{last}",
    "import ZInQKernel.Contrib.OneProof.T10NarrowReaders",
    "",
    "/-! Local Tate-duality bypass. Generated by `scratch/t10-narrow/gen_bypass.py`. -/",
    "",
    "set_option linter.style.longLine false",
    "set_option autoImplicit false",
    "",
    "namespace HDec.HSyn",
    "",
]
axioms = []
for path, name in locs:
    structure = name == "OpenAddedLeaves28"
    line, decl = extract(path, name, "structure" if structure else "theorem")
    if structure:
        decl = field_only(decl)
    else:
        axioms.append(f"#print axioms HDec.HSyn.{replacements[name]}")
    text += [f"-- Copied from {path}:{line} ({name}).", replace(decl), ""]
    print(f"{path}:{line}\t{name}\t{replacements[name]}")
CHAIN.write_text("\n".join(text + ["end HDec.HSyn", "", *axioms, ""]))

_, original = extract(MAIN, "_root_.ZInQ.OneProof.frozenTarget")
DRY.write_text(
    "import ZInQKernel.OneProof.Main\n"
    "import ZInQKernel.OneProof.Discharges\n"
    "import ZInQKernel.Contrib.OneProof.T10NarrowChain\n"
    "import Lean\n\n"
    "/-! Generated top, with the base headline imported as a closure control. -/\n\n"
    + replace(original.replace("theorem _root_.", "theorem ", 1))
    + "\n\n#print axioms ZInQ.OneProof.frozenTarget_t10\n\n"
    + (SCRATCH / "DryRunChecks.lean.txt").read_text()
)
print(f"{MAIN}\tfrozenTarget\tfrozenTarget_t10")

rows, columns = autofold.load_kinds()
old_row, = [r for r in rows if r["field"] == "t10TateDuality"]
new_row = dict(
    old_row,
    field="t10TateDualityLocal",
    flag=("pending review: finite F/Q_p, l = p, all dimensions; drops arbitrary K and independent l, "
          "including positive characteristic and its algebraic/separable closure comparison. "
          "Rem. 12.5 states equivariance without proof; notes unrefereed (ruling open). "
          "Pro-etale/classical etale comparison is on the spot."),
    source=("Milne, Abelian Varieties v2.0, Part I, Thm 12.1(a) p. 55 with Rem. 12.5 p. 56; "
            "diophantine_zq.tex L10966-10972. Bhatt-Scholze, The pro-etale topology for schemes, "
            "section 5.6 (locator UNVERIFIED)."),
    rated_by="pending review",
)
new_row["flag_class"] = autofold.flag_class(new_row["flag"], new_row["strict"], new_row["strictest"])
after = [new_row if r is old_row else r for r in rows]
problems = render_open.kinds_row_problems(new_row, {r["field"] for r in after}, set())
assert not problems, problems
assert render_open.must_be_glue(new_row["flag"])
assert autofold.counts(rows) == autofold.counts(after) == (29, 5, 24, 5, 24)
with (SCRATCH / "kinds-row.tsv").open("w") as f:
    writer = csv.DictWriter(f, fieldnames=columns, delimiter="\t", lineterminator="\n")
    writer.writeheader()
    writer.writerow(new_row)
for label, rs in [("before", rows), ("after", after)]:
    n, leaf, glue, leafest, glueest = autofold.counts(rs)
    print(f"{label}: {len(rs)} total; H {n}, strict {leaf}/{glue}, strictest {leafest}/{glueest}")
