"""Degree-6 maps J : P^1_u -> P^1_j that pull the Shimura orbifold X^6/W = P^1_j(4, 6, 2)
(special values j = 0, infinity, -16/27 of orders 4, 6, 2; manuscript lines 409-441) back to
P^1_u with exactly five cone points of order 2, the candidate contacts.

The 11/5 proof of H uses J only through its ramification over the three special values (lines
545-563), so a non-Galois J would serve as well as the dihedral quotient of degree 12.
Orbifold Euler characteristic: -1/2 = N * (-1/12) forces N = 6 for an orbifold covering.
Passports (cycle types over 0, infinity, -16/27) with five points of order 2:
  (a) [2,2,2] [3,3] [2,2,2]   with the poles at 0 and infinity, J = k A^2/u^3 and k A^2 - j1 u^3 = k B^2
                              give (A - B)(A + B) = (j1/k) u^3, so A = (alpha + beta u^3)/2: the
                              contacts over 0 are cube roots of one number, never all rational.
  (b) [2,2,2] [6]   [2,2,1,1] J = c A(u)^2 with A cubic: polynomial Pell identity.
  (c) [2,4]   [6]   [2,1,1,1,1]
  (d) [2,4]   [3,3] [2,2,1,1]
These are three-point covers, so each passport has finitely many solutions up to Moebius maps.
"""
import sympy as sp

u, w, q, lam, c = sp.symbols('u w q lam c')
j1 = sp.Rational(-16, 27)

# (b): after a rational affine change C = mu (w^2 - 1), and the solutions of A^2 - C B^2 = const
# with deg A = 3 are multiples of T_3(w) = 4w^3 - 3w (the unit group of Qbar[w][sqrt(w^2-1)]
# modulo constants is generated by w + sqrt(w^2 - 1)).
print("(b) roots of T_3:", sp.solve(sp.chebyshevt(3, w), w), "-> never all rational")

# (c): put the e = 6 point at infinity, the e = 2 contact at 0 and the e = 4 point at 1:
# J = c u^2 (u - 1)^4; the remaining critical point is 1/3 and must map to j1.
J = c * u**2 * (u - 1)**4
cs = sp.solve(sp.Eq(J.subs(u, sp.Rational(1, 3)), j1), c)[0]
print("(c) c =", cs, "; J - j1 over Q:", sp.factor(sp.expand(J.subs(c, cs) - j1)))

# (d): put the e = 4 point at 0, the e = 2 contact at 1 and one pole at infinity:
# J = k (u - 1)^2 u^4 / (u - q)^3.  Other critical points: roots of D = 3u^2 - (6q+1)u + 4q.
# Both must lie over j1: g = (u-1)^2 u^4 - lam (u - q)^3 must be divisible by D (lam = j1/k).
# Reduce g modulo D by hand: replace u^2 by ((6q+1)u - 4q)/3 repeatedly.
def reduce_mod_D(poly):
    p = sp.Poly(sp.expand(poly), u)
    D = sp.Poly(3*u**2 - (6*q + 1)*u + 4*q, u)
    return sp.Poly(sp.rem(p.as_expr(), D.as_expr(), u), u)

r = reduce_mod_D((u - 1)**2 * u**4 - lam * (u - q)**3)
coeffs = [sp.numer(sp.together(cf)) for cf in r.all_coeffs()]
# both coefficients are linear in lam: eliminate lam
a0 = [sp.Poly(cf, lam) for cf in coeffs]
res = sp.factor(sp.resultant(coeffs[0], coeffs[1], lam))
print("(d) eliminant in q:", res)
for fac, mult in sp.factor_list(res)[1]:
    fq = sp.Poly(fac, q)
    print("   factor of degree", fq.degree(), ":", fac)
    for qv in sp.roots(fq, filter='Q') if fq.degree() == 1 else []:
        if qv in (0, 1):
            print("     degenerate q =", qv); continue
        lv = sp.solve(coeffs[0].subs(q, qv), lam)
        for l in lv:
            if l == 0:
                continue
            g = sp.Poly(sp.expand((u - 1)**2 * u**4 - l * (u - qv)**3), u)
            Dq = sp.Poly(sp.expand(3*u**2 - (6*qv + 1)*u + 4*qv), u)
            quo, rem = sp.div(g, Dq**2)
            print("     q =", qv, "lam =", l, "exact:", rem.is_zero,
                  "simple points over j1:", sp.factor(quo.as_expr()))

# The rational solution of (d): q = 1/2, k = j1/lam = 1/2.  After u -> 1/u the five contacts are
# the integers -1, 0, 1, 2, 3 and J5(u) = 4 (u - 1)^2 / (u^3 (2 - u)^3).
J5 = 4 * (u - 1)**2 / (u**3 * (2 - u)**3)
print("J5 =", J5)
print("  J5 - 0     numerator:", sp.factor(sp.numer(sp.together(J5))), " (zero of order 4 at infinity)")
print("  1/J5       numerator:", sp.factor(sp.numer(sp.together(1 / J5))))
print("  J5 - j1    numerator:", sp.factor(sp.numer(sp.together(J5 - j1))))
dJ = sp.factor(sp.numer(sp.together(sp.diff(J5, u))))
print("  critical points:", dJ)
# ramification of the normalized pullback of the orbifold P^1_j(4, 6, 2): index e / gcd(e, a)
def pull_index(order, a):
    from math import gcd
    return order // gcd(order, a)
data = {'0': (4, {'u=1': 2, 'u=oo': 4}), 'oo': (6, {'u=0': 3, 'u=2': 3}),
        'j1': (2, {'u=-1': 1, 'u=3': 1, 'roots of 3u^2-4u+2 (after u->1/u: 2u^2-4u+3)': 2})}
for jv, (order, pts) in data.items():
    for pt, a in pts.items():
        print("  over j=%s: %s has J-ramification %d, pulled-back index %d" % (jv, pt, a, pull_index(order, a)))
