"""Split /tmp/no5_all.lean into ZInQKernel/Contrib/OneProof/CMBranch/No5{A,B,...}.lean (< ~130 KB each) at depth-0
boundaries, each importing the previous one."""
import os
D=os.path.expanduser('~/dzq-wt/cm-branch/ZInQKernel/Contrib/OneProof/CMBranch/')
s=open('/tmp/no5_all.lean').read()
lines=s.split('\n')
depth=0; cuts=[]
for i,l in enumerate(lines):
    w=l.split()
    if not w: continue
    if w[0]=='namespace' and ' end ' not in l: depth+=1
    elif w[0]=='section' or l.startswith('noncomputable section'): depth+=1
    elif w[0]=='end': depth-=1
    if depth==0 and (w[0]=='end' or l.startswith('-- ==== end')): cuts.append(i)
LIM=125000
parts=[]; start=0; size=0; last_ok=None
pos=[0]
for l in lines: pos.append(pos[-1]+len(l)+1)
cur_start=0
for c in cuts:
    if pos[c+1]-pos[cur_start] > LIM and last_ok is not None:
        parts.append((cur_start,last_ok)); cur_start=last_ok+1
    last_ok=c
parts.append((cur_start,len(lines)-1))
pre='''{imp}

/-! # cm-branch, R5ptProps prune (dry run, part {part}): No5 copies

Generated by `scratch/cm-branch/gen/gen_no5.py` (+ `no5_edits.py`, `no5_split.py`): every declaration in the
closure of `sixContactMin_of_open67_cm` that (transitively) mentions the moduli row's conjunct
`LeafQM.AV.R5ptProps` (González–Rotger Thm 5.12 on `X₆`), copied verbatim from its module with the module's
scope commands, every copied name `c` renamed `c_no5`, and `R5ptProps` replaced by `R5ptProps_no5 := True`.
Hand edits are marked `-- cm-branch edit`.
-/
'''
prelude='''
namespace LeafQM.AV
open CategoryTheory AlgebraicGeometry
/-- `R5ptProps` (González–Rotger Thm 5.12 on `X₆`) replaced by `True` in the pruned row. -/
def R5ptProps_no5 (X : Over (Spec (CommRingCat.of ℚ)))
    (Ψ : (fieldPt Qbar ⟶ X) ≃ Quotient (pairSetoid Qbar)) : Prop := True
end LeafQM.AV

'''
names='ABCDEFGH'
for f in os.listdir(D):
    if f.startswith('No5') and f.endswith('.lean'): os.remove(D+f)
for k,(a,b) in enumerate(parts):
    imp='import ZInQKernel.Contrib.OneProof.CMBranch.Top' if k==0 else 'import ZInQKernel.Contrib.OneProof.CMBranch.No5'+names[k-1]
    txt=pre.format(imp=imp, part=names[k])+(prelude if k==0 else '')+'\n'.join(lines[a:b+1])+'\n'
    open(D+'No5'+names[k]+'.lean','w').write(txt)
    print(names[k], len(txt))
