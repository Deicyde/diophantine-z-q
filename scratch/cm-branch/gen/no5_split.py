"""Split /tmp/no5_all.lean into ZInQKernel/Contrib/OneProof/CMBranch/No5{A,B,...}.lean (< ~125 KB each). A cut may
fall inside open scopes: the part is closed with `end`s and the next part re-opens the scope stack (namespace/section
lines with their open/set_option/variable lines)."""
import os
D=os.path.expanduser('~/dzq-wt/cm-branch/ZInQKernel/Contrib/OneProof/CMBranch/')
s=open('/tmp/no5_all.lean').read()
lines=s.split('\n')
stack=[]  # frames: [open_line, name, [extra lines]]
cuts=[]   # (line index after which we may cut, snapshot of stack)
import copy
for i,l in enumerate(lines):
    w=l.split()
    if w:
        if w[0]=='namespace' and ' end ' not in l: stack.append([l, w[1], []])
        elif w[0]=='section': stack.append([l, w[1] if len(w)>1 else '', []])
        elif l.startswith('noncomputable section'): stack.append([l, w[2] if len(w)>2 else '', []])
        elif w[0]=='end':
            if stack: stack.pop()
        elif w[0] in ('open','set_option','variable') and not l.rstrip().endswith(' in') and stack:
            stack[-1][2].append(l)
    # cut allowed after a blank line that follows a complete declaration (heuristic: next line starts a decl/doc)
    if l.strip()=='' and i+1<len(lines) and (lines[i+1].startswith(('theorem','/--','def ','structure','noncomputable def','-- ====','namespace','section','end'))):
        cuts.append((i, copy.deepcopy(stack)))
LIM=125000
pos=[0]
for l in lines: pos.append(pos[-1]+len(l)+1)
parts=[]; cur=0; cur_stack=[]; last=None
for (c,st) in cuts:
    if pos[c+1]-pos[cur] > LIM and last is not None:
        parts.append((cur,last[0],cur_stack,last[1])); cur=last[0]+1; cur_stack=last[1]
    last=(c,st)
parts.append((cur,len(lines)-1,cur_stack,[]))
pre='''{imp}

/-! # cm-branch, R5ptProps prune (dry run, part {part}): No5 copies

Generated by `scratch/cm-branch/gen/gen_no5.py` (+ `no5_edits.py`, `no5_split.py`): every declaration in the
closure of `sixContactMin_of_open67_cm` that (transitively) mentions the moduli row's conjunct
`LeafQM.AV.R5ptProps` or the field types `GonzalezRotgerThm512X6(RCF)` (González–Rotger Thm 5.12), copied
verbatim from its module with the module's scope commands, every copied name `c` renamed `c_no5`,
`R5ptProps` replaced by `R5ptProps_no5 := True`, and the González–Rotger fields deleted. Hand edits are marked
`-- cm-branch edit`.
-/
'''
prelude='''
namespace LeafQM.AV
open CategoryTheory AlgebraicGeometry
/-- `R5ptProps` (González–Rotger Thm 5.12 on `X₆`) replaced by `True` in the pruned row. -/
def R5ptProps_no5 (X : Over (Spec (CommRingCat.of ℚ)))
    (Ψ : (fieldPt Qbar ⟶ X) ≃ Quotient (pairSetoid Qbar)) : Prop := True
end LeafQM.AV

'''
names='ABCDEFGHIJ'
for f in os.listdir(D):
    if f.startswith('No5') and f.endswith('.lean'): os.remove(D+f)
for k,(a,b,st_in,st_out) in enumerate(parts):
    imp='import ZInQKernel.Contrib.OneProof.CMBranch.Top' if k==0 else 'import ZInQKernel.Contrib.OneProof.CMBranch.No5'+names[k-1]
    reopen=''.join(fr[0]+'\n'+''.join(x+'\n' for x in fr[2]) for fr in st_in)
    close=''.join('end'+((' '+fr[1]) if fr[1] else '')+'\n' for fr in reversed(st_out))
    txt=pre.format(imp=imp, part=names[k])+(prelude if k==0 else '')+reopen+'\n'.join(lines[a:b+1])+'\n'+close
    open(D+'No5'+names[k]+'.lean','w').write(txt)
    print(names[k], len(txt))
