#!/bin/bash
# Generate SplitCheck.lean = scratch/g0-split/Split.lean + §2-§5 of Product.lean (names moved to
# HSyn.G0Split) + HSyn.glueOutputs_of_leaves_g0product (ProductExists discharged).
# Needs `lake build ZInQKernel.Hypotheses.JHeight ZInQKernel.Compiler.Precision.HeightConstant`.
# Check: lake env lean scratch/g0-product/SplitCheck.lean
cd "$(dirname "$0")"
P=Product.lean; S=../g0-split/Split.lean
start=$(grep -n "^/-! ## §2" $P | cut -d: -f1)
{ cat $S; echo
  echo "/-! ## g0-product (appended for the integration check; generated by mkcheck.sh) -/"
  echo "noncomputable section"
  tail -n +$start $P | grep -v "^#print axioms" | sed 's/G0Split\./HSyn.G0Split./g'
  cat <<'EOF'

/-- `HSyn.glueOutputs_of_leaves` with the hypothesis `ProductExists` discharged by
`G0Product.productExists`. -/
theorem HSyn.glueOutputs_of_leaves_g0product (r : HSyn.ResearchLeaves) (t : HSyn.TextbookLeaves)
    (hR18 : HSyn.G0Split.R18_JavanpeykarConcrete) (hR22 : HSyn.G0Split.R22_PazukiConcrete)
    (hDimF : HSyn.G0Split.DimFinite) (hDim : HSyn.G0Split.DimBaseChange)
    (hBelyi : HSyn.G0Split.X1BelyiOnModel) (hSimp : HSyn.G0Split.FibreSimple)
    (hAdd : HSyn.G0Split.HeightAdditivity) (hBC : HSyn.G0Split.StableHeightBaseChange)
    (hRev : HSyn.G0Split.ReverseIsogeny) (hThetaPt : HSyn.G0Split.ThetaPointOfFibre)
    (hMod : HSyn.G0Split.ModularConstituent) :
    GlueAssembly.GlueOutputs ZInQ.Mult.S_mul :=
  HSyn.glueOutputs_of_leaves r t hR18 hR22 hDimF hDim hBelyi hSimp hAdd hBC
    G0Product.productExists hRev hThetaPt hMod

end

#print axioms G0Product.productExists
#print axioms HSyn.glueOutputs_of_leaves_g0product
EOF
} > SplitCheck.lean
