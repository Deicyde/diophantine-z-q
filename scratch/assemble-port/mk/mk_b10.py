import re
d='scratch/infra-stalks/'
rd=lambda p: open(d+p).read()
noprint=lambda s: '\n'.join(l for l in s.split('\n') if not l.startswith('#print'))
sp=rd('StalkPullback.lean'); body=sp[sp.index('universe u'):]
cp=rd('CotangentProduct.lean'); cpbody=cp[cp.index('namespace IsLocalRing'):]
ls=noprint(rd('local_structure.lean.part'))
opens='''namespace ZInQ.HeightBC

open CategoryTheory AlgebraicGeometry Limits MonoidalCategory CartesianMonoidalCategory MonObj
open NumberField DefFaltings
'''
ula=noprint(rd('ula_proof.lean.part')).replace('open PkgI3 (AbVar)\n','')
hdr='''/-! ## g0-assemble3: infra-stalks (scratch/infra-stalks/), generated by mk/mk_b10.py
Contents, verbatim except as noted: `StalkPullback.lean` from `universe u` on; `local_structure.lean.part`;
`CotangentProduct.lean` from `namespace IsLocalRing` on (general lemmas, Mathlib only); `ker_proof.lean.part`
and `mulN_proof.lean.part` (mul-rigidity's `KerUnitOpenOfCotangentSurj`, `CotangentMulN`, hence
`MulRigidity.mulIsogeny : G0FibreSimple.MulIsogeny`; mul-rigidity's `Mul.lean` text is already in part a15);
the `namespace ZInQ.HeightBC` header of `assemble_hbc.py` (without `open PkgI3 (AbVar)`, deleted as in part
a20), `bc_proof.lean.part`, `ula_proof.lean.part` (its `open PkgI3 (AbVar)` deleted likewise) and
`hbc_final.lean.part` (height-bc's `CotangentSpanBC`, `UniformizationLiftAnalytic`; height-bc's `Final.lean`
text is already in part a20). All `#print axioms` lines dropped. -/
'''
out=[hdr,body,'',ls,'',cpbody,'',noprint(rd('ker_proof.lean.part')),'',noprint(rd('mulN_proof.lean.part')),'',
     opens,noprint(rd('bc_proof.lean.part')),'',ula,'',noprint(rd('hbc_final.lean.part'))]
open('scratch/assemble-port/parts/b10_stalks.lean','w').write('\n'.join(out))
