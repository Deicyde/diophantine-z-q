"""Section 5.1 check on actual curves: for d = 5 (mod 8) squarefree with dim Sel_2(C_d) = 3 and a
first coordinate a of Sel_2(C_d) with |a| = 7 (mod 8) (the hypotheses of CR_3 after Proposition 0),
verify T_5b(d) = 1 directly from class groups, and (where PARI finds a generator quickly) that C_d has
a point of infinite order with x in a Q*^2.

Sel_2 is computed here by an independent full 2-descent: local Kummer images W_v of
E(Q_v)/2E(Q_v) for v in {inf, 2, p | d} are generated by local points (x, x - d) until they reach the
known dimension (1 at inf, 3 at 2, 2 at odd p), and Sel_2 = {(b1, b2) in G^2 : loc_v(b1, b2) in W_v}.
"""
import sys
import os
import random
from fractions import Fraction
from itertools import product as iproduct
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from genus import primes_of, g_redei_parity, set_partitions, prod, disc, rank_f2
import cypari2

pari = cypari2.Pari()
pari.allocatemem(2 * 10**9)
MINP = int(os.environ.get("MINP", "2"))


def vp(n, p):
    v = 0
    while n % p == 0:
        n //= p
        v += 1
    return v, n


def local_class(q, p):
    """Class of nonzero rational q in Q_p*/Q_p*^2 as a bit tuple."""
    q = Fraction(q)
    if p == 0:
        return (1 if q < 0 else 0,)
    a, b = q.numerator, q.denominator
    va, ua = vp(a, p)
    vb, ub = vp(b, p)
    v, u = va - vb, ua * ub  # same square class as ua/ub
    if p == 2:
        u8 = u % 8
        return (v % 2, 1 if u8 in (3, 7) else 0, 1 if u8 in (3, 5) else 0)
    leg = pow(u % p, (p - 1) // 2, p)
    return (v % 2, 0 if leg == 1 else 1)


def is_local_square(q, p):
    return q != 0 and all(c == 0 for c in local_class(q, p))


def kummer(x, d):
    if x == 0:
        return (Fraction(-d * d), Fraction(-d))
    if x == d:
        return (Fraction(d), Fraction(2 * d * d))
    if x == -d:
        return (Fraction(-d), Fraction(-2 * d))
    return (Fraction(x), Fraction(x - d))


def span(vecs):
    S = {tuple(0 for _ in vecs[0])}
    for v in vecs:
        S |= {tuple(a ^ b for a, b in zip(s, v)) for s in S}
    return S


def local_image(d, p, rng):
    target = {0: 1, 2: 3}.get(p, 2)
    vecs = []
    for x in (0, d, -d):
        a, b = kummer(Fraction(x), d)
        vecs.append(local_class(a, p) + local_class(b, p))
    tries = 0
    while rank_f2([list(v) for v in vecs]) < target:
        tries += 1
        assert tries < 200000, (d, p)
        if p == 0:
            x = Fraction(rng.randint(-3 * d, 3 * d), rng.randint(1, 5))
        else:
            j = rng.randint(0, 3)
            x = Fraction(rng.randint(-10**8, 10**8), p ** (2 * j)) + (d if rng.random() < 0.3 else 0)
        if x in (0, d, -d):
            continue
        f = x**3 - d * d * x
        if p == 0:
            ok = f > 0
        else:
            ok = is_local_square(f, p)
        if ok:
            a, b = kummer(x, d)
            vecs.append(local_class(a, p) + local_class(b, p))
    return span(vecs)


def selmer(d, rng):
    ps = primes_of(d)
    places = [0, 2] + ps
    W = {p: local_image(d, p, rng) for p in places}
    gens = [-1, 2] + ps
    G = []
    for bits in iproduct((0, 1), repeat=len(gens)):
        G.append(prod(g for g, b in zip(gens, bits) if b))
    sel = []
    for b1 in G:
        for b2 in G:
            if all(local_class(b1, p) + local_class(b2, p) in W[p] for p in places):
                sel.append((b1, b2))
    return sel


def T5b(d):
    ps = primes_of(d)
    g = {}
    tot = 0
    for pi in set_partitions(ps):
        bl = [prod(B) for B in pi]
        cl = sorted(b % 8 for b in bl)
        if cl.count(7) == 1 and cl.count(3) == 1 and cl.count(1) == len(cl) - 2:
            w = 1
            for b in bl:
                if b not in g:
                    g[b] = g_redei_parity(b)
                w *= g[b]
            tot += w
    return tot % 2


def sqfree_class_eq(x, a):
    q = Fraction(x) / a
    return q > 0 and pari.issquare(pari(f"{q.numerator}/{q.denominator}"))


def point_check(d, a):
    E = pari.ellinit([0, 0, 0, -d * d, 0])
    try:
        r = pari('(E)->iferr(alarm(20, ellrank(E)), e, 0)')(E)
    except BaseException:
        return "timeout"
    if r == 0 or len(r[3]) == 0:
        return "no point found"
    P = r[3][0]
    for T in ([0, 0], [d, 0], [-d, 0], [0]):
        Q = pari.elladd(E, P, T) if T != [0] else P
        x = Fraction(str(Q[0]))
        if x != 0 and sqfree_class_eq(x, a):
            return f"point with x/a square found (rank bounds {r[0]}..{r[1]})"
    return f"NO point with x in aQ*^2 among P+T (rank bounds {r[0]}..{r[1]})"


if __name__ == "__main__":
    rng = random.Random(51 + MINP)
    want = int(sys.argv[1]) if len(sys.argv) > 1 else 30
    found = tried = 0
    while found < want:
        d = rng.randrange(21, 2 * 10**6, 8)
        assert d % 8 == 5
        try:
            ps = primes_of(d)
        except AssertionError:
            continue
        if len(ps) < MINP or len(ps) > 6:
            continue
        tried += 1
        sel = selmer(d, rng)
        if len(sel) != 8:
            continue
        firsts = {b1 for b1, _ in sel}
        cand = [a for a in firsts if abs(a) % 8 == 7]
        if not cand:
            continue
        found += 1
        a = cand[0]
        t = T5b(d)
        pc = point_check(d, a) if d < 3 * 10**5 else "skipped (large)"
        print(f"d={d} primes={ps} a={a} |Sel2|=8 T5b={t} :: {pc}", flush=True)
    print(f"tried {tried} squarefree d, kept {found}")
