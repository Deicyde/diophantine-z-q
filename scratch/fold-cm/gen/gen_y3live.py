"""fold-cm component 2: y3-x6b's gen_y3b.py retargeted on fold-cm's CM route (the live chain of fold-c8).

Input: cm-branch2's weak-row copies ZInQKernel/Contrib/OneProof/CMBranch/R5Prune{1,2,3,}.lean (the bottom of the chain)
and fold-cm's ZInQKernel/OneProof/H/CMR5_1, CMR5_2, CMR5 (the live chain's weak-row copies). y3-x6b's transformations
(DELETE, REPLACE, PATCH, field_ops of scratch/y3-x6b/gen/gen_y3b.py, imported) with
  * the bost-gr9 (GR9) entries of y3-x6b replaced by their live-chain copies (`..._sf_u_c8`, `..._sf_u`);
  * every copied name suffixed `_y3c` (y3-x6b's `_y3` names are taken by its own Contrib/OneProof/Y3X6/Copy*.lean).
Output: ZInQKernel/OneProof/H/Y3Copy{1..n}.lean.
"""
import re, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '../../y3-x6b/gen'))
import gen_y3b as G
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../..'))
H = os.path.join(ROOT, 'ZInQKernel/OneProof/H/')

DELETE = set(G.DELETE) - {'HDec.HSyn.GR9.SGRFold.heckeSqrtBranchAny_of_open29_hf_gm_pz_eb',
                          'HDec.HSyn.GR9.openResearchLeaves34_of_OpenResearchLeaves35_eb_cf'}
DELETE |= {'HDec.HSyn.GR9.SGRFold.heckeSqrtBranchAny_of_open29_hf_gm_pz_eb_sf_u_c8',
           # the live weak conversion 35 -> 34 (reads x6CoarseModuli / elkiesX6StarEvery); TailZ's conversion replaces it
           'HDec.HSyn.GR9.openResearchLeaves34_of_OpenResearchLeaves35_eb_cf_sf_u',
           # the top chain theorems above generation 45 inline that conversion; the new top calls open45 directly
           'HDec.HSyn.GR9.sixContactMin_of_open72_sf_u_hm_cm', 'HDec.HSyn.sixContactMin_of_open79_hm_cm',
           'HDec.HSyn.sixContactMin_of_open80_cm'}
PATCH = [p for p in G.PATCH if not p[0].startswith('HDec.HSyn.GR9.')]
PATCH += [
 ('HDec.HSyn.GR9.x6Rows_of_open14_hf_gm_pz_eb_sf_u_c8', G.PATCH[3][1], G.PATCH[3][2]),
 ('HDec.HSyn.GR9.openGlue7_of_OpenGlue8_hf_gm_pz_eb_sf_u_c8',
  '''  heckeSqrtBranchAny := _root_.HDec.HSyn.GR9.SGRFold.heckeSqrtBranchAny_of_open29_hf_gm_pz_eb_sf_u_c8_y3
    (_root_.HDec.HSyn.GR9.openResearchLeaves22_of_OpenResearchLeaves23_gm_eb_sf_u_y3
      (_root_.HDec.HSyn.GR9.openResearchLeaves23_of_OpenResearchLeaves24_hf_gm_eb_sf_u_y3 (_root_.HDec.HSyn.GR9.openResearchLeaves24_of_OpenResearchLeaves25_gm_eb_sf_u_y3 r) t)) t l''',
  '''  heckeSqrtBranchAny := r.heckeSqrtY3'''),
]
Y3 = re.compile(r'_y3(?![A-Za-z0-9])')


def main():
    files = [G.SRC + f + '.lean' for f in ('CMBranch/R5Prune1', 'CMBranch/R5Prune2', 'CMBranch/R5Prune3', 'CMBranch/R5Prune')]
    files += [H + f + '.lean' for f in ('CMR5_1', 'CMR5_2', 'CMR5')]
    allb = []
    for f in files:
        allb += G.blocks_of(f)
    used = set(); out = []
    for b in allb:
        n = G.name_of(b)
        if n in DELETE: continue
        b = G.R5.sub('_y3', b)
        b = b.replace('-- cm-branch2 (hand-written)', '-- (cm-branch2 hand-written block)')
        if n in G.REPLACE: b = G.replace_block(b, G.REPLACE[n])
        for (pn, old, new) in PATCH:
            if pn == n:
                assert old in b, ('PATCH', pn, old[:60])
                b = b.replace(old, new); used.add((pn, old))
        b = G.field_ops(b)
        out.append(Y3.sub('_y3c', b))
    assert len(used) == len(PATCH), ('unused patches', [p[0] for p in PATCH if (p[0], p[1]) not in used])
    for d in DELETE: assert any(G.name_of(b) == d for b in allb), ('DELETE not found', d)
    for r in G.REPLACE: assert any(G.name_of(b) == r for b in allb), ('REPLACE not found', r)
    header = ('/-! # fold-cm: the CM-branch route of the live chain with the moduli row over `Y₃` (no `X₆`), generated by\n'
              '`scratch/fold-cm/gen/gen_y3live.py` (y3-x6b\'s generator on fold-cm\'s chain) from the weak-row copies\n'
              '`Contrib/OneProof/CMBranch/R5Prune*.lean` and `OneProof/H/CMR5*.lean`: every declaration is a verbatim copy with\n'
              '`_r5` renamed `_y3c`, except y3-x6\'s hand-written replacements and deletions (the row is `Y3X6.R1R2fpY3`;\n'
              'the carried `X₆` fields become `y3row` and `heckeSqrtY3`). -/\n\n'
              'set_option maxHeartbeats 1000000\nset_option autoImplicit false\nset_option linter.style.longLine false\n\n')
    parts, cur = [], ''
    for b in out:
        if len((cur + b).encode()) > 140000 and cur:
            parts.append(cur); cur = ''
        cur += b
    parts.append(cur)
    names = [f'Y3Copy{i + 1}' for i in range(len(parts))]
    for i, (nm, body) in enumerate(zip(names, parts)):
        imp = ('import ZInQKernel.OneProof.H.CMOpen\nimport ZInQKernel.Contrib.OneProof.Y3X6.Row' if i == 0
               else f'import ZInQKernel.OneProof.H.{names[i - 1]}')
        open(H + nm + '.lean', 'w').write(imp + '\n\n' + header.replace('-/', f'Part {i + 1} of {len(parts)}. -/', 1) + body)
    print('parts', names, len(out), 'blocks')
    txt = ''.join(out)
    for w in ['gonzalezRotgerX6Ab', 'babaGranathRationalAb', 'elkiesX6StarPrinted', 'elkiesX6StarFunctionField',
              'elkiesEquationsX6Ab', 'x6Rows_of_leavesW', 'X6LeavesW', 'x6CoarseModuli', 'elkiesX6StarEvery']:
        for m in re.finditer(r'.*\b' + w + r'\b.*', txt):
            print('LEFT', w, '|', m.group(0)[:160])


if __name__ == '__main__':
    main()
