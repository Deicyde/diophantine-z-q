"""fold-cm component 1: switch Main.lean to TailZ88 / sixContactMin_of_open81 / OpenResearchLeaves62 and update kinds.tsv
(drop research/gonzalezRotgerThm512X6RCF; add the five CM rows of scratch/cm-fold-rebase/kinds-rows.tsv, every leaf
flag prefixed 'pending review' so it counts GLUE until rated). Never touches claims.tsv or volatile.tsv.
Each textual edit asserts its pattern (the script stops if Main.lean changed)."""
import csv, io, os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../..'))
os.chdir(ROOT)
M = 'ZInQKernel/OneProof/Main.lean'
s = open(M).read()
PAR = '''
fold-cm (the CM-branch package, cm-branch, cm-branch2, cox-lattice and cm-fold-rebase; Jack's ruling, verbatim: "Fold now
at +4 (Recommended)") replaced the base of the chain, NoCM (FS5, from González–Rotger's Thm 5.12 on `X₆`, its count and the
`X₆` Kummer fibre), by the manuscript's CM branch (L581-631): the research field `gonzalezRotgerThm512X6RCF` is no longer
read, and the CM-branch inputs `cmFibreSplit` (glue), `fowlerProp27`, `cmjDegree`, `cmPotentialGood` and `cmHeight62`
(leaves pending review) are fields. `OpenResearchLeaves62` (`TailZ88`) is the new generation, and
`HDec.HSyn.sixContactMin_of_open81` goes through the chain of `sixContactMin_of_open80` with the CM inputs threaded and the
CM branch at its base (`Contrib/OneProof/CMBranchUC8.lean`, `OneProof/H/CMTopLive.lean`), the moduli row carried in its
weak form (`R5ptProps` as `True`, `OneProof/H/CMR5*.lean`) and the bundles without the field (`OneProof/H/CMOpen.lean`);
generated by `scratch/fold-cm/gen/`; copy reroute; no existing declaration is changed.
'''
reps = [('import ZInQKernel.OneProof.H.TailZ87\n', 'import ZInQKernel.OneProof.H.TailZ88\n'),
        ('    (r : HDec.HSyn.OpenResearchLeaves61) (t : HDec.HSyn.OpenTextbookLeaves18) (l : HDec.HSyn.OpenAddedLeaves28)',
         '    (r : HDec.HSyn.OpenResearchLeaves62) (t : HDec.HSyn.OpenTextbookLeaves18) (l : HDec.HSyn.OpenAddedLeaves28)'),
        ('    (HDec.HSyn.sixContactMin_of_open80 r t l) hPC', '    (HDec.HSyn.sixContactMin_of_open81 r t l) hPC'),
        ('is changed.\n\nThe hypotheses of `frozenTarget` are therefore exactly the open statements.',
         'is changed.\n' + PAR + '\nThe hypotheses of `frozenTarget` are therefore exactly the open statements.')]
for a, b in reps:
    assert s.count(a) == 1, a
    s = s.replace(a, b)
open(M, 'w').write(s)

K = 'docs/one-proof/kinds.tsv'
rows = list(csv.reader(open(K), delimiter='\t'))
hdr, body = rows[0], rows[1:]
n0 = len(body)
body = [r for r in body if not (r[0] == 'research' and r[1] == 'gonzalezRotgerThm512X6RCF')]
assert len(body) == n0 - 1
new = [r for r in csv.reader(open('scratch/cm-fold-rebase/kinds-rows.tsv'), delimiter='\t')
       if r and not r[0].startswith('#') and r[0] != 'bundle']
assert len(new) == 5 and all(len(r) == 13 for r in new)
for r in new:
    if r[2] in ('published', 'consequence'):
        r[3] = 'pending review (new leaf, GLUE until a reviewer rates it); ' + r[3]
        r[11] = 'pending-review'
    r[7] = r[7].replace('cm-fold-rebase (cm-branch, cm-branch2)', 'fold-cm (cm-branch, cm-branch2, cm-fold-rebase)')
    assert r[4] == 'GLUE' and r[5] == 'GLUE'
    assert not r[3].startswith('unread')
order = []
for r in body:
    if r[0] not in order: order.append(r[0])
out = []
for b in order:
    grp = [r for r in body if r[0] == b] + [r for r in new if r[0] == b]
    if b == 'research':
        grp.sort(key=lambda r: r[1].lower())
    out += grp
buf = io.StringIO()
w = csv.writer(buf, delimiter='\t', lineterminator='\n')
w.writerow(hdr); w.writerows(out)
open(K, 'w').write(buf.getvalue())
print('Main.lean switched; kinds.tsv:', n0, '->', len(out), 'rows')
