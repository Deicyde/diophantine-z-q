"""fold-cm: thread the CM-branch inputs through the live chain of the head's top (cm-fold-rebase's mk_top3.py on
fold-c8's chain).

Walks the head's top `HDec.HSyn.sixContactMin_of_open<N>` (TailZ<k>.lean) down through the one-step chain theorems
of `OneProof/H/C8Chain.lean` to the base `sixContactMin_of_open4_hf_pz_eb_u_c8`, and copies each verbatim, in its own
namespace and context, with `(c : CMBranch.CMInputs3)` threaded and the callee renamed `<callee>_cm (c := c)`.
The base is replaced by `sixContactMin_of_open4_hf_pz_eb_u_c8_cm` := CMBranchUC8's `sixContactMin_of_open4_cm_u_c8`
with `ReducedCMPeriod` and `HeightAdditivityUpper` proved (cm-branch2) and `CoxProperLattice` proved (cox-lattice).
Usage: python3 scratch/fold-cm/gen/mk_top_live.py TOPFILE TOPNAME OUT
"""
import re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
import leanctx
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../..'))
TOPFILE, TOPNAME, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
import glob
# the head's TailZ file, every later research-only autofold TailZ (k >= 87), and fold-c8's chain
FILES = sorted({os.path.join(ROOT, TOPFILE)} | {f for f in glob.glob(os.path.join(ROOT, 'ZInQKernel/OneProof/H/TailZ*.lean'))
               if re.fullmatch(r'TailZ(\d+)\.lean', os.path.basename(f)) and int(re.findall(r'\d+', os.path.basename(f))[0]) >= 87
               and 'fold-cm' not in open(f).read()}) + [os.path.join(ROOT, 'ZInQKernel/OneProof/H/C8Chain.lean')]
BASE = 'sixContactMin_of_open4_hf_pz_eb_u_c8'

def find(name):
    hits = []
    for F in FILES:
        L = leanctx.lines_of(F)
        for i, l in enumerate(L):
            if re.match(r'^theorem ' + re.escape(name) + r'(?=[\s(])', l):
                hits.append((F, i))
    if not hits: return None
    assert len(hits) == 1, (name, hits)
    F, a = hits[0]; L = leanctx.lines_of(F); b = a + 1
    while b < len(L) and (L[b].startswith(' ')): b += 1
    return F, a, b

chain = []
cur = TOPNAME
while cur != BASE:
    r = find(cur)
    assert r is not None, cur
    F, a, b = r
    L = leanctx.lines_of(F)
    t = '\n'.join(L[a:b]).rstrip()
    body = t.split('ZInQ.SixContactMin :=', 1)[1]
    calls = [c for c in re.findall(r"(sixContactMin_of_[A-Za-z0-9_']+)", body) if c != cur]
    assert len(set(calls)) == 1, (cur, calls)
    chain.append((cur, F, a, b, calls[0])); cur = calls[0]
out = []
for name, F, a, b, callee in reversed(chain):
    L = leanctx.lines_of(F)
    t = '\n'.join(L[a:b]).rstrip()
    i = t.index('ZInQ.SixContactMin :=')
    j = t.rindex(':', 0, i)
    sig = t[:j].rstrip() + ' (c : _root_.HDec.CMBranch.CMInputs3) ' + t[j:i] + 'ZInQ.SixContactMin :='
    sig = sig.replace('theorem ' + name, 'theorem ' + name + '_cm', 1)
    body = t[i + len('ZInQ.SixContactMin :='):]
    assert len(re.findall(r'(?<![\w\'])' + re.escape(callee) + r'(?![\w\'])', body)) == 1, (name, callee)
    body = re.sub(r'(?<![\w\'])' + re.escape(callee) + r'(?![\w\'])', callee + '_cm (c := c)', body)
    ns, ctx = leanctx.context(F, a + 1)
    rel = os.path.relpath(F, ROOT)
    blk = [f'-- copied from {rel}:{a + 1} ({ns}.{name}), c threaded', 'section', f'namespace {ns}'] + ctx + [
           f'/-- `{name}` with the base switched to the manuscript\'s CM branch (`sixContactMin_of_open4_hf_pz_eb_u_c8_cm`); '
           'generated by `scratch/fold-cm/gen/mk_top_live.py`. -/',
           sig + body, f'end {ns}', 'end', '']
    out.append('\n'.join(blk))
base = '''section
namespace HDec.HSyn
/-- The base: CMBranchUC8's `sixContactMin_of_open4_cm_u_c8` (the manuscript's CM branch, L581-631, on the live
bundles) with `ReducedCMPeriod` and `HeightAdditivityUpper` proved from the textbook fields `t35`, `homLatticeCorr`,
`t11b` (cm-branch2) and `CoxProperLattice` proved (cox-lattice). -/
theorem sixContactMin_of_open4_hf_pz_eb_u_c8_cm (r : OpenResearchLeaves2EBU) (t : OpenTextbookLeaves4HFPZ)
    (l : OpenAddedLeaves4PZC8) (g : OpenGlue4) (h20 : G0Split.R20Lower) (hYu : QMLattice.YuB6Alg)
    (hθ : PkgI1.QMHauptmodul → G0Split.ThetaPt.ThetaSplit.ThetaRatiosAtQM) (c : _root_.HDec.CMBranch.CMInputs3) :
    ZInQ.SixContactMin :=
  sixContactMin_of_open4_cm_u_c8 r t l g h20 hYu hθ c.cmFibreSplit c.fowlerProp27 c.cmjDegree
    c.cmPotentialGood c.cmHeight62
    (CMBranch.reducedCMPeriod_of_leaves t.t35 t.homLatticeCorr t.t11b CMBranch.coxProperLattice_proof)
    (CMBranch.heightAdditivityUpper_of_t35 t.t35)
end HDec.HSyn
end

'''
hdr = f'''import ZInQKernel.OneProof.H.{os.path.basename(TOPFILE)[:-5]}
import ZInQKernel.Contrib.OneProof.CMBranchUC8
import ZInQKernel.Contrib.OneProof.CMBranch2

/-! # fold-cm: the live chain with the manuscript's CM branch (generated by `scratch/fold-cm/gen/mk_top_live.py`)

Each one-step theorem of the head's chain, from `{TOPNAME}` down to fold-c8's base
`sixContactMin_of_open4_hf_pz_eb_u_c8` (FS5 / NoCM), is copied verbatim with the CM-branch inputs
`c : CMBranch.CMInputs3` threaded and its callee renamed `…_cm (c := c)`; the base is the manuscript's CM branch
(`CMBranchUC8.lean`). The originals are unchanged. -/

set_option maxHeartbeats 1000000
set_option linter.style.longLine false
noncomputable section

'''
open(os.path.join(ROOT, OUT), 'w').write(hdr + base + '\n'.join(out) + '\nend\n')
print(len(chain), [c[0] for c in chain])
