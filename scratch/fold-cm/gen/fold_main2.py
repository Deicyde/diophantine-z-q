"""fold-cm component 2: switch Main.lean to TailZ89 / sixContactMin_of_open82 / OpenResearchLeaves63 and update kinds.tsv
(drop x6CoarseModuliIdeal, elkiesX6StarEveryIdeal; add y3ToP1j (consequence, flag beginning 'pending review') and
heckeSqrtBranchAny (glue; its Y3-only argument labelled on-the-spot) from scratch/y3-x6b/kinds-rows.tsv).
Never touches claims.tsv or volatile.tsv. Each textual edit asserts its pattern."""
import csv, io, os
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../..'))
os.chdir(ROOT)
M = 'ZInQKernel/OneProof/Main.lean'
s = open(M).read()
PAR = '''Its second component (y3-x6b, with y3-p1j and y3-x6) replaced the `X₆` witness of the moduli row by the row over
`Y₃` (`Y3X6.R1R2fpY3`, L411-526): the research fields `x6CoarseModuliIdeal` and `elkiesX6StarEveryIdeal` are no longer
read, and `y3ToP1j` (the manuscript's map `Y₃ → P¹_j`, L420-440; leaf pending review) and `heckeSqrtBranchAny` (glue,
formerly derived from Elkies' model of `X₆`; its `Y₃`-only argument is on the spot) are fields. `OpenResearchLeaves63`
(`TailZ89`) is the new generation, and `HDec.HSyn.sixContactMin_of_open82` goes through `OneProof/H/Y3Copy*.lean` and
`OneProof/H/Y3Open.lean` (generated by `scratch/fold-cm/gen/`; copy reroute).
'''
reps = [('import ZInQKernel.OneProof.H.TailZ88\n', 'import ZInQKernel.OneProof.H.TailZ89\n'),
        ('    (r : HDec.HSyn.OpenResearchLeaves62) (t : HDec.HSyn.OpenTextbookLeaves18)',
         '    (r : HDec.HSyn.OpenResearchLeaves63) (t : HDec.HSyn.OpenTextbookLeaves18)'),
        ('    (HDec.HSyn.sixContactMin_of_open81 r t l) hPC', '    (HDec.HSyn.sixContactMin_of_open82 r t l) hPC'),
        ('generated by `scratch/fold-cm/gen/`; copy reroute; no existing declaration is changed.\n',
         'generated by `scratch/fold-cm/gen/`; copy reroute; no existing declaration is changed.\n' + PAR)]
for a, b in reps:
    assert s.count(a) == 1, a
    s = s.replace(a, b)
open(M, 'w').write(s)

K = 'docs/one-proof/kinds.tsv'
rows = list(csv.reader(open(K), delimiter='\t'))
hdr, body = rows[0], rows[1:]
n0 = len(body)
rm = {('research', 'x6CoarseModuliIdeal'), ('research', 'elkiesX6StarEveryIdeal')}
body = [r for r in body if (r[0], r[1]) not in rm]
assert len(body) == n0 - 2
new = [r for r in csv.reader(open('scratch/y3-x6b/kinds-rows.tsv'), delimiter='\t') if r and r[0] != 'bundle']
assert [r[1] for r in new] == ['y3ToP1j', 'heckeSqrtBranchAny'] and all(len(r) == 13 for r in new)
y, h = new
y[3] = 'pending review (new leaf, GLUE until a reviewer rates it); ' + y[3]
y[11] = 'pending-review'
h[3] = ('on-the-spot: the Y3-only argument (the quadratic subcover of Y3 -> P^1_j ramified over -16/27 and oo gives the '
        'global square root) is not in the manuscript, whose route (L481-526) is local; ' + h[3])
h[11] = h[11] or 'note'
for r in new:
    r[7] = r[7].replace('y3-x6b (fold)', 'y3-x6b, fold-cm (fold)') if 'fold' in r[7] else r[7] + ', fold-cm (fold)'
    if not r[12]: r[12] = 'elliotglazer/diophantine-z-q#86'
    assert r[4] == 'GLUE' and r[5] == 'GLUE' and not r[3].startswith('unread')
order = []
for r in body:
    if r[0] not in order: order.append(r[0])
out = []
for b in order:
    grp = [r for r in body if r[0] == b] + [r for r in new if r[0] == b]
    if b == 'research': grp.sort(key=lambda r: r[1].lower())
    out += grp
buf = io.StringIO()
w = csv.writer(buf, delimiter='\t', lineterminator='\n')
w.writerow(hdr); w.writerows(out)
open(K, 'w').write(buf.getvalue())
print('Main.lean switched; kinds.tsv:', n0, '->', len(out), 'rows')
