def weaken_struct(B, k):
    out, n = [], 0
    for l in B:
        if re.match(r'^  sga7_IX_3_3_SH : _root_\.SGA7PersistsNF\.SGA7_IX_3_3_SH\s*$', l):
            out.append(f'  sga7_IX_3_3_SH : {AC}'); n += 1
        elif re.match(r'^  sga7_IX_3_3 : _root_\.CToPrinted\.SGA7_IX_3_3\s*$', l):
            out.append(f'  sga7_IX_3_3 : {CP}'); n += 1
        else:
            out.append(l)
    if n != 1:
        sys.exit(f'generation {k}: weakened {n} field lines')
    # replace the weakened field's docstring
    i = next(i for i, l in enumerate(out) if re.match(r'^  sga7_IX_3_3(_SH)? : ', l))
    if out[i - 1].rstrip().endswith('-/'):
        d = i - 1
        while not out[d].lstrip().startswith('/--'):
            d -= 1
        out[d:i] = ['  /-- sga33-shpre: weakened to ' + ('SGA7_IX_3_3_SHpreAC (the new leaf).' if k >= 20 else
                    'SGA7_IX_3_3cp (from the new leaf by SGA7PreAC.sga7_IX_3_3cp_of_preAC).') + ' -/']
    out[0:0] = [f'/-- sga33-shpre bypass copy of `HDec.HSyn.OpenResearchLeaves{k}` with the SGA 7 IX 3.3 field weakened '
                f'(`{AC.split(".")[-1] if k >= 20 else CP.split(".")[-1]}`). -/']
    # drop the original docstring (first docstring lines before 'structure')
    s = next(i for i, l in enumerate(out) if l.startswith('structure '))
    return [out[0]] + out[s:]


def replace_line(B, pat, new, what):
    hits = [i for i, l in enumerate(B) if re.match(pat, l)]
    if len(hits) != 1:
        sys.exit(f'{what}: {len(hits)} hits for {pat}')
    i = hits[0]
    # drop continuation lines of that field (deeper indentation)
    j = i + 1
    while j < len(B) and B[j].startswith('    ') and not re.match(r'^  \w+ :=', B[j]):
        j += 1
    return B[:i] + [new] + B[j:]


