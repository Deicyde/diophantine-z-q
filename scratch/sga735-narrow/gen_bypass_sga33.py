"""Generate scratch/sga33-shpre/Bypass.lean: the fold of SGA7_IX_3_3_SHpre -> SGA7_IX_3_3_SHpreAC (a weaker leaf).

The new leaf cannot fill the old field, so the fold copies every bundle generation that carries the field
(research generations 14..27, as `sga7_IX_3_3_SH` in 20..27 and as `sga7_IX_3_3` in 14..19) into the namespace
`HDec.HSyn.SHpreBypass`, with the field's type weakened (SGA7_IX_3_3_SHpreAC in 20..27, SGA7_IX_3_3cp in 14..19),
copies every theorem on the route that takes one of those bundles (maps, helpers, the stack theorems 17..37),
and edits the four lines that read the field. Name resolution inside the namespace picks the copies.
Run from the repository root:  python3 scratch/sga33-shpre/gen_bypass.py > scratch/sga33-shpre/Bypass.lean
"""
import re, sys

H = 'ZInQKernel/OneProof/H/'
NL = '\n'


def lines(fn):
    return open(fn).read().split(NL)


def block_from(L, i):
    """Lines from i to the first blank line (exclusive), with the docstring right above i."""
    j = i
    while j < len(L) and L[j].strip() != '':
        j += 1
    k = i
    # include the docstring immediately above
    if k > 0 and L[k - 1].rstrip().endswith('-/'):
        k -= 1
        while not L[k].lstrip().startswith('/--'):
            k -= 1
    return L[k:j]


def get_decl(fn, kind, name):
    L = lines(fn)
    for i, l in enumerate(L):
        if re.match(rf'^{kind} {re.escape(name)}\b', l):
            return block_from(L, i)
    sys.exit(f'not found: {kind} {name} in {fn}')


def struct_block(fn, name):
    L = lines(fn)
    for i, l in enumerate(L):
        if l.startswith(f'structure {name} : Prop where'):
            j = i + 1
            while j < len(L) and L[j].strip() != '' and not L[j].startswith(('theorem', 'def', 'structure', 'end')):
                j += 1
            k = i
            if L[k - 1].rstrip().endswith('-/'):
                k -= 1
                while not L[k].lstrip().startswith('/--'):
                    k -= 1
            return L[k:j]
    sys.exit(f'structure {name} not found in {fn}')


