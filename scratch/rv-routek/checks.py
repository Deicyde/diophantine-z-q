from itertools import permutations
from fractions import Fraction
import cmath
class np:
    """minimal stand-in for numpy (not installed)"""
    @staticmethod
    def exp(z): return cmath.exp(z)
    pi = cmath.pi
    class M:
        def __init__(self, rows): self.r = [list(map(complex, x)) for x in rows]
        @property
        def shape(self): return (len(self.r), len(self.r[0]))
        def __matmul__(self, o):
            n, k, m = len(self.r), len(o.r), len(o.r[0])
            return np.M([[sum(self.r[i][t]*o.r[t][j] for t in range(k)) for j in range(m)] for i in range(n)])
        def __setitem__(self, idx, val):
            (a, b) = idx
            for i in range(a.start, a.stop):
                for j in range(b.start, b.stop):
                    self.r[i][j] = val.r[i-a.start][j-b.start]
    @staticmethod
    def array(rows): return np.M(rows)
    @staticmethod
    def zeros(sh, dtype=None): return np.M([[0]*sh[1] for _ in range(sh[0])])
    @staticmethod
    def eye(n): return np.M([[1 if i == j else 0 for j in range(n)] for i in range(n)])
    @staticmethod
    def allclose(a, b): return all(abs(x-y) < 1e-9 for ra, rb in zip(a.r, b.r) for x, y in zip(ra, rb))

ok_all = True
def check(name, cond):
    global ok_all
    ok_all &= bool(cond)
    print(("OK   " if cond else "FAIL ") + name)

# 1. Constants (N5: G0 = |GL4(F5)|, U0 = 4(D G0)^2, E0 = 10(D G0)^2).
def gl(n, q):
    r = 1
    for i in range(n):
        r *= q**n - q**i
    return r
G0 = gl(4, 5)
GL4Z4 = 2**16 * gl(4, 2)          # kernel of GL4(Z/4) -> GL4(F2) is 1 + 2M4, order 2^16
