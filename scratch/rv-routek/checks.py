# 2. alt's claim (ii): the degree forced by odd nebentypus at p in T_- is
#    prod 2^(v2(p-1)-1) <= prod (p-1)/2 <= m <= 2 R^R M: polynomial in M.
def v2(n):
    k = 0
    while n % 2 == 0:
        n //= 2; k += 1
    return k
import sympy
