check("2^(v2(p-1)-1) <= (p-1)/2 for odd p < 2000", all(2**(v2(p-1)-1) <= (p-1)//2 for p in ps))

# 3. Finite-group model of Mackey/Ind facts used by G14 and G16 (G = S4).
G = list(permutations(range(4)))
def mul(a, b): return tuple(a[b[i]] for i in range(4))     # (ab)(i) = a(b(i))
def inv(a):
    r = [0]*4
    for i, x in enumerate(a): r[x] = i
    return tuple(r)
def sign(p):
    s, seen = 1, set()
    for i in range(4):
        if i in seen: continue
        j, c = i, 0
        while j not in seen:
            seen.add(j); j = p[j]; c += 1
        s *= (-1)**(c-1)
    return s
e = tuple(range(4))
A4 = [g for g in G if sign(g) == 1]
V4 = [e, (1,0,3,2), (2,3,0,1), (3,2,1,0)]
def induce(H, rep):
    """matrices of Ind_H^G rep, rep: dict H -> d x d matrix"""
    reps = []
    for g in G:
        if not any(mul(inv(r), g) in H for r in reps): reps.append(g)
    d = next(iter(rep.values())).shape[0]; k = len(reps)
    out = {}
    for g in G:
        M = np.zeros((k*d, k*d), dtype=complex)
        for j, rj in enumerate(reps):
            for i, ri in enumerate(reps):
                h = mul(inv(ri), mul(g, rj))
                if h in H: M[i*d:(i+1)*d, j*d:(j+1)*d] = rep[h]
        out[g] = M
    return out
# characters of A4: the order-3 characters, nontrivial on A4/V4
w = np.exp(2j*np.pi/3)
c3 = (1,2,0,3)  # a 3-cycle
def a4char(k):
    rep = {}
    for h in A4:
        # coset of h in A4/V4 ~ Z/3 generated by c3
        for t in range(3):
            g = e
            for _ in range(t): g = mul(g, c3)
            if mul(inv(g), h) in V4: rep[h] = np.array([[w**(k*t)]]); break
    return rep
for k in range(3):
    I = induce(A4, a4char(k))
    hom = all(np.allclose(I[mul(a, b)], I[a] @ I[b]) for a in G for b in G)
    triv = all(np.allclose(I[n], np.eye(I[n].shape[0])) for n in V4)
    check(f"Ind_A4^S4 chi^{k}: homomorphism, V4 (normal in S4, inside ker chi) acts trivially", hom and triv)
# a normal subgroup N of G contained in H but NOT acting trivially on V: Ind is nontrivial on N
sgn_on_V4 = {h: np.array([[1.0]]) if h in [e, (1,0,3,2)] else np.array([[-1.0]]) for h in V4}
I = induce(V4, sgn_on_V4)
check("control: V4-character nontrivial on V4 gives Ind nontrivial on V4", not all(np.allclose(I[n], np.eye(6)) for n in V4))
# Frobenius reciprocity dimension: <r, Ind_H^G (r|H)>_G = <r|H, r|H>_H, r = 2-dim irrep of S4
def char2(g):   # 2-dim irrep of S4 via S4 -> S3: character = (#fixed points on 3 pairings) - 1
    pairings = [((0,1),(2,3)), ((0,2),(1,3)), ((0,3),(1,2))]
    def act(P): return frozenset(frozenset((g[a], g[b])) for a, b in P)
    return sum(1 for P in pairings if act(P) == frozenset(frozenset(x) for x in P)) - 1
def inner(chi, psi, grp): return Fraction(sum(chi(g)*psi(g) for g in grp), len(grp))
# Ind_H^G char: (1/|H|) sum_{x in G, x^-1 g x in H} chi(x^-1 g x)
def indchar(chiH, H):
    return lambda g: Fraction(sum(chiH(mul(inv(x), mul(g, x))) for x in G if mul(inv(x), mul(g, x)) in H), len(H))
for H, nm in [(A4, "A4"), (V4, "V4")]:
    lhs = inner(char2, indchar(char2, H), G)
    rhs = inner(char2, char2, H)
    check(f"Frobenius reciprocity <r, Ind_{nm} r|> = <r|,r|>_{nm} = {rhs}", lhs == rhs and lhs > 0)
print("ALL OK:", ok_all)
