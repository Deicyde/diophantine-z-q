"""y3-x6: the top bundle generation without the two X6 fields (ZInQKernel/Contrib/OneProof/Y3X6/Top.lean), from
cm-branch2's CMBranch/Open73.lean: verbatim except the field lines named below and `_r5` -> `_y3`."""
import re, os
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '../../..'))
src = open(os.path.join(ROOT, 'ZInQKernel/Contrib/OneProof/CMBranch/Open73.lean')).read()
L = src.split('\n')

DROP = ('x6CoarseModuliIdeal', 'elkiesX6StarEveryIdeal', 'x6CoarseModuli', 'elkiesX6StarEvery',
        'gonzalezRotgerX6Ab', 'elkiesX6StarFunctionField')
NEWF = ['  /-- y3-p1j (leaf, kind consequence, flag ELLIOT): the manuscript\'s map `Y₃ → P¹_j` (diophantine_zq.tex L420-440; normalizer quotient cited to Baba–Granath and Lin–Yang at L420-422): on every fine witness, `π : Y → P¹` with fibres = `Aut 𝒪`-twist classes, CM values `0, ∞, −16/27` exactly at discriminants `−4, −3, −24`, onto `P¹(ℚ̄)`, fibres of at most 324 points (`Y3P1j.Y3ToP1j`). -/',
        '  y3ToP1j : _root_.Y3P1j.Y3ToP1j',
        '  /-- y3-x6 (glue, open): sgr-direct\'s `HeckeSqrtBranchAny` (for a triple with R1fp, R1hecke, R2fp and a Galois `E/ℚ(X)` with the normalization chart, `E ∋ √(c(27X + 16))`, `c ∈ ℚ^×`), formerly derived from Elkies\' model of `X₆`; on the `Y₃` route it is the quadratic subcover of `Y₃ → P¹_j` ramified over `−16/27` and `∞` (the branch indices `4, 6, 2` at L421-422, L500; docs/research/y3-x6.md §4). -/',
        '  heckeSqrtBranchAny : SGRDirect.HeckeSqrtBranchAny']

out = []
i = 0
mode = None
def finish():
    hdr = next(x for x in reversed(out) if x.startswith('structure ') or x.startswith('theorem '))
    if hdr.startswith('structure '):
        out.extend(NEWF)
    elif ' where' in hdr and 'openResearchLeaves34_r5_of_35_cm' in hdr:
        out.append('  y3row := n.y3ToP1j')
        out.append('  heckeSqrtY3 := n.heckeSqrtBranchAny')
    elif ' where' in hdr:
        out.append('  y3ToP1j := n.y3ToP1j')
        out.append('  heckeSqrtBranchAny := n.heckeSqrtBranchAny')
while i < len(L):
    l = L[i]
    if l.startswith('structure '):
        mode = 'struct'
    elif l.startswith('theorem '):
        mode = 'thm'
    m = re.match(r'^  (\w+) (:=?) ', l)
    if m and m.group(1) in DROP:
        j = i + 1
        while j < len(L) and L[j].startswith('    '): j += 1
        if m.group(2) == ':' and out and out[-1].startswith('  /--'):
            out.pop()
        i = j
        if mode in ('struct', 'thm') and not (L[j] if j < len(L) else '').startswith('  '):
            finish()
            mode = None
        continue
    out.append(l)
    # after the last field of a structure / conversion, append the new fields
    nxt = L[i + 1] if i + 1 < len(L) else ''
    if mode in ('struct', 'thm') and l.startswith('  ') and not nxt.startswith('  '):
        finish()
        mode = None
    i += 1
t = '\n'.join(out)
t = re.sub(r'_r5(?![A-Za-z0-9])', '_y3', t)
t = t.replace('OpenResearchLeaves54CM', 'OpenResearchLeaves55Y3')
t = t.replace('OpenResearchLeaves36EBCF_cm', 'OpenResearchLeaves36EBCF_y3x6').replace('OpenResearchLeaves35EBCF_cm', 'OpenResearchLeaves35EBCF_y3x6')
t = t.replace('openResearchLeaves36EBCF_cm_of_54', 'openResearchLeaves36EBCF_y3x6_of_55').replace('openResearchLeaves35_cm_of_36_cm', 'openResearchLeaves35_y3x6_of_36')
t = t.replace('openResearchLeaves34_r5_of_35_cm', 'openResearchLeaves34_y3_of_35_y3x6').replace('openResearchLeaves34_y3_of_35_cm', 'openResearchLeaves34_y3_of_35_y3x6')
t = t.replace('sixContactMin_of_open73_cm', 'sixContactMin_of_open74_y3x6')
t = t.replace('import ZInQKernel.Contrib.OneProof.CMBranch2', 'import ZInQKernel.Contrib.OneProof.Y3X6.Copy3')
# header docstring
k = t.index('/-!'); e = t.index('-/', k) + 2
t = t[:k] + '''/-! # y3-x6: the fold's next generation without the two `X₆` fields (generated by `scratch/y3-x6/gen/gen_top.py`)

`OpenResearchLeaves55Y3` is cm-branch2's `OpenResearchLeaves54CM` without `x6CoarseModuliIdeal` and
`elkiesX6StarEveryIdeal`, with y3-p1j's leaf `y3ToP1j` (`Y3P1j.Y3ToP1j`, the manuscript's map `Y₃ → P¹_j`) and the
glue `heckeSqrtBranchAny` (`SGRDirect.HeckeSqrtBranchAny`, formerly a theorem from Elkies' model of `X₆`). The two
intermediate bundles are copied without `x6CoarseModuli`, `elkiesX6StarEvery` and with the two new fields; the last
conversion fills the `Y₃`-route bundle `OpenResearchLeaves34EBCF_y3` (`Y3X6/Copy*.lean`). `sixContactMin_of_open74_y3x6`
is the top theorem: `ZInQ.SixContactMin` from the open statements alone, with no `X₆` in the closure. -/''' + t[e:]
t = t.replace('''/-- **G0 with only the open statements, the CM branch of the manuscript in place of NoCM** (cm-branch2 fold):
`gonzalezRotgerThm512X6RCF` removed; `CMFibreSplit`, `FowlerProp27`, `CMjDegree`, `CMPotentialGood`, `CMHeight62` added. -/''',
'''/-- **G0 with only the open statements, the CM branch of the manuscript, and the moduli row over `Y₃`** (y3-x6 fold, on
cm-branch2's): `x6CoarseModuliIdeal` and `elkiesX6StarEveryIdeal` removed; `y3ToP1j` (leaf) and `heckeSqrtBranchAny` (glue)
added. No `X₆` witness, no `X6Props`, `R2X6Props`, `CMExists`, `X6Surj` in the closure (scratch/y3-x6/closure.txt). -/''')
open(os.path.join(ROOT, 'ZInQKernel/Contrib/OneProof/Y3X6/Top.lean'), 'w').write(t)
print('ok')
