"""fold34-eichler: write the new top module (autofold's shape) over the copy OneProof/H/EichlerBoundCopy.lean (gen.py)
and patch Main.lean. Run from the repository root, after gen.py:
  python3 scratch/fold34-eichler/gen/top.py
Reads the current top from Main.lean (`sixContactMin_of_openN r t l`, the bundle types of r, t, l); the new module is
the next TailZ number. `gagaMorphism` and `mumfordTorsionAlgClosed` are taken from the textbook bundle when it has
them (so the fold replays before or after a fold that proves them); otherwise the expression with which the chain
fills them is reused. Asserts every edit."""
import re, glob

H = "ZInQKernel/OneProof/H/"
MAINP = "ZInQKernel/OneProof/Main.lean"
main = open(MAINP).read()
ft = re.search(r"theorem _root_\.ZInQ\.OneProof\.frozenTarget\n.*?\n(?=end ZInQ\.Contrib\.TYZChain)", main, re.S).group(0)
B = dict((v, t) for v, t in re.findall(r"\((\w) : HDec\.HSyn\.(\w+)\)", ft))
R, T, L = B["r"], B["t"], B["l"]
TOP = re.search(r"HDec\.HSyn\.(sixContactMin_of_open(\d+)) r t l\)", ft)
TOPN, N = TOP.group(1), int(TOP.group(2))
tops = [int(m) for m in re.findall(r"^import ZInQKernel\.OneProof\.H\.TailZ(\d+)$", main, re.M)]
OLDMOD = "TailZ%d" % max(tops)
ZFILES = sorted((int(m.group(1)), f) for f in glob.glob(H + "TailZ*.lean") for m in [re.search(r"TailZ(\d+)\.lean$", f)] if m)
NEWMOD = "TailZ%d" % (ZFILES[-1][0] + 1)
NEWR = "OpenResearchLeaves%d" % (int(re.search(r"\d+$", R).group(0)) + 1)
NEWTOP = "sixContactMin_of_open%d" % (N + 1)
copy = open(H + "EichlerBoundCopy.lean").read()
assert re.search(r"^theorem %s_eb \(r : %sEB\) \(t : %s\) \(l : %s\)" % (TOPN, R, T, L), copy, re.M), "copy top"
assert not glob.glob(H + NEWMOD + ".lean")


def struct_body(text, name):
    m = re.search(r"^structure " + name + r" : Prop where\n((?:  .*\n|\n)*?)(?=^\S)", text, re.M)
    assert m, name
    return m.group(1)


def find_struct(name):
    for f in sorted(glob.glob(H + "*.lean")):
        s = open(f).read()
        if re.search(r"^structure " + name + r" : Prop where", s, re.M):
            return struct_body(s, name)
    raise SystemExit("no " + name)


rb = find_struct(R).rstrip("\n") + "\n"
rnames = re.findall(r"^  (\w+) :", rb, re.M)
assert "gonzalezRotgerProp56X6" in rnames
parts = re.split(r"(?=^  (?:/--|\w+ :))", rb, flags=re.M)
# glue each docstring to its field
fields, cur = [], ""
for p_ in parts:
    cur += p_
    if re.match(r"^  \w+ :", p_):
        fields.append(cur); cur = ""
assert not cur.strip() and len(fields) == len(rnames)
kept = [f for f in fields if not re.search(r"^  gonzalezRotgerProp56X6 :", f, re.M)]
assert len(kept) == len(fields) - 1
newbody = "".join(kept)

tb = find_struct(T)
tnames = re.findall(r"^  (\w+) :", tb, re.M)


def textbook(fld):
    if fld in tnames:
        return "t." + fld
    # the chain fills it: reuse the newest such assignment
    for _, f in reversed(ZFILES):
        m = re.search(r"^  " + fld + r" := (_root_\.[\w.']+)$", open(f).read(), re.M)
        if m:
            return m.group(1)
    raise SystemExit("no source for " + fld)


GAGA, TORS = textbook("gagaMorphism"), textbook("mumfordTorsionAlgClosed")
conv = "".join(
    (f"  gonzalezRotgerProp56X6 := _root_.EichlerBound.r5fpCountLe_of_two {GAGA} {TORS}\n" if f == "gonzalezRotgerProp56X6"
     else f"  {f} := n.{f}\n") for f in rnames)
out = f'''import ZInQKernel.OneProof.H.{OLDMOD}
import ZInQKernel.OneProof.H.EichlerBoundCopy

/-! # OneProof H, fold34-eichler (eichler-bound): `{NEWTOP}` (written by fold34-eichler's top.py after autofold's pattern)

Field removed: the research field `gonzalezRotgerProp56X6` (GLUE: González–Rotger 2006 Prop. 5.6 at `(D, N) = (6, 1)`,
the count `#CM(R) = 2^{{b(R)}} h(R)` on `X₀(6, 1)`). Fields added: none. The chain reads the count only as the upper
bound `GR56.R5fpCountLe`, which eichler-bound proved with no leaf (`EichlerBound.r5fpCountLe_proof`: gr56-prove's
`#CM(R) ≤ #(Emb(R, 𝒪)/𝒪^×)` and an explicit injection `Emb(R, 𝒪)/𝒪^× ↪ Pic(R) × T`, `#T = 2^{{b(R)}}`), from the proved
`uniformizationLeafAll` and the textbook fields `gagaMorphism`, `mumfordTorsionAlgClosed`
(`EichlerBound.r5fpCountLe_of_two`, `Contrib/OneProof/R5fpCountLeHF.lean`). A weaker statement cannot fill the old
field, so its readers are rerouted by a copy: `ZInQKernel/OneProof/H/EichlerBoundCopy.lean` (generated by
`scratch/fold34-eichler/gen/gen.py`) copies every declaration of `{TOPN}`'s proof that reads a count field or takes a
bundle carrying one, with the count fields typed `GR56.R5fpCountLe`. The originals, including `{R}` and `{TOPN}`, are
unchanged. -/

namespace HDec

namespace HSyn

/-- **The research leaves still open** (fold34-eichler, eichler-bound): `{R}` without `gonzalezRotgerProp56X6` (no
replacement field). {len(kept)} fields. -/
structure {NEWR} : Prop where
{newbody}
/-- `{R}EB` (the copy of `{R}` with the count field typed `GR56.R5fpCountLe`) from `{NEWR}`: the bound by
`EichlerBound.r5fpCountLe_of_two` from the textbook fields. -/
theorem {R[0].lower() + R[1:]}EB_of_{NEWR} (n : {NEWR}) (t : {T}) : {R}EB where
{conv}
/-- **G0 with only the open leaves** (fold34-eichler; `gonzalezRotgerProp56X6` removed with no new leaf). -/
theorem {NEWTOP} (r : {NEWR}) (t : {T}) (l : {L}) : ZInQ.SixContactMin :=
  {TOPN}_eb ({R[0].lower() + R[1:]}EB_of_{NEWR} r t) t l

end HSyn

end HDec

#print axioms HDec.HSyn.{NEWTOP}
'''
open(H + NEWMOD + ".lean", "w").write(out)

DOC_OLD = "\nThe hypotheses of `frozenTarget` are therefore exactly the open statements."
DOC_NEW = f'''
fold34-eichler (eichler-bound) then removed the research field `gonzalezRotgerProp56X6` (GLUE) with no new leaf: the
chain reads González–Rotger's count only as the bound `GR56.R5fpCountLe`, proved by `EichlerBound.r5fpCountLe_proof`
(from `uniformizationLeafAll`, `gagaMorphism`, `mumfordTorsionAlgClosed`). `{NEWR}` (`{NEWMOD}`) is `{R}` without it,
and `HDec.HSyn.{NEWTOP}` goes through `{TOPN}_eb` (`OneProof/H/EichlerBoundCopy.lean`, generated by
`scratch/fold34-eichler/gen/gen.py`), a copy of every declaration that reads a count field or takes a bundle carrying
one, with the count fields typed `GR56.R5fpCountLe`. The originals are unchanged.
''' + DOC_OLD
for old, new in [
    (f"import ZInQKernel.OneProof.H.{OLDMOD}\n", f"import ZInQKernel.OneProof.H.{NEWMOD}\n"),
    (f"(r : HDec.HSyn.{R})", f"(r : HDec.HSyn.{NEWR})"),
    (f"(HDec.HSyn.{TOPN} r t l)", f"(HDec.HSyn.{NEWTOP} r t l)"),
    (DOC_OLD, DOC_NEW),
]:
    if main.count(old) != 1:
        raise SystemExit("Main: " + old)
    main = main.replace(old, new)
open(MAINP, "w").write(main)
print(f"{NEWMOD} written: {NEWR}, {NEWTOP} over {TOPN}_eb; gaga: {GAGA}; torsion: {TORS}; Main patched")
